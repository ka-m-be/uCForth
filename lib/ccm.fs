\ ccm.fs - CCM with a 13-byte nonce and an 8-byte tag (RFC 3610)
\ AES128 must be loaded and keyed first. Payload changes in place.
PACKAGE CCM  ALSO AES128
: NEED-32 ( -- )  CELL 4 <> ABORT" CCM needs 32-bit cells" ; NEED-32
16 BUFFER: MAC
16 BUFFER: CTR
16 BUFFER: STREAM
13 BUFFER: NONCE
VARIABLE AAD-A  VARIABLE AAD-N
VARIABLE PAY-A  VARIABLE PAY-N
VARIABLE TAG-A  VARIABLE USED
VARIABLE BUSY
VARIABLE STAGE
VARIABLE POSITION
VARIABLE DECRYPTING
: BE16! ( x a -- )  OVER 8 RSHIFT OVER C! 1+ C! ;
: PARAMETERS ( nonce aad an payload pn tag -- )
  >R DUP 0 65536 WITHIN 0= ABORT" bad CCM payload length"
  >R >R DUP 0 65280 WITHIN 0= ABORT" bad CCM AAD length"
  AAD-N ! AAD-A ! NONCE 13 MOVE R> PAY-A ! R> PAY-N ! R> TAG-A ! ;
: MAC-BYTE ( c -- )
  MAC USED @ + DUP C@ ROT XOR SWAP C! 1 USED +!
  USED @ 16 = IF MAC MAC AES128-ENCRYPT 0 USED ! THEN ;
: MAC-ADD ( a n -- )  0 ?DO DUP C@ MAC-BYTE 1+ LOOP DROP ;
: PAD-MAC ( -- )  USED @ IF MAC MAC AES128-ENCRYPT 0 USED ! THEN ;
: AUTH ( -- )
  MAC 16 0 FILL
  AAD-N @ IF $59 ELSE $19 THEN MAC C!
  NONCE MAC 1+ 13 MOVE PAY-N @ MAC 14 + BE16!
  MAC MAC AES128-ENCRYPT 0 USED !
  AAD-N @ IF
    AAD-N @ 8 RSHIFT MAC-BYTE AAD-N @ $FF AND MAC-BYTE
    AAD-A @ AAD-N @ MAC-ADD PAD-MAC
  THEN
  PAY-A @ PAY-N @ MAC-ADD PAD-MAC ;
: COUNTER ( n -- )
  CTR 16 0 FILL 1 CTR C! NONCE CTR 1+ 13 MOVE CTR 14 + BE16!
  CTR STREAM AES128-ENCRYPT ;
: CRYPT ( -- )
  PAY-N @ 15 + 16 / 0 ?DO
    I 1+ COUNTER
    PAY-N @ I 16 * - 16 MIN 0 ?DO
      PAY-A @ J 16 * + I + DUP C@ STREAM I + C@ XOR SWAP C!
    LOOP
  LOOP ;
: MAKE-TAG ( -- )  0 COUNTER 8 0 DO MAC I + DUP C@ STREAM I + C@ XOR SWAP C! LOOP ;
: WIPE ( -- )
  MAC 16 0 FILL CTR 16 0 FILL STREAM 16 0 FILL NONCE 13 0 FILL 0 USED ! ;

PUBLIC
: CCM-ENCRYPT ( nonce aad an payload pn tag -- )
  BUSY @ ABORT" CCM is busy"
  PARAMETERS AUTH MAKE-TAG MAC TAG-A @ 8 MOVE CRYPT WIPE ;
: CCM-DECRYPT ( nonce aad an payload pn tag -- )
  BUSY @ ABORT" CCM is busy"
  PARAMETERS CRYPT AUTH MAKE-TAG
  0 8 0 DO MAC I + C@ TAG-A @ I + C@ XOR OR LOOP
  WIPE IF PAY-A @ PAY-N @ 0 FILL -411 THROW THEN ;

PRIVATE
: BEGIN-AUTH ( -- )
  MAC 16 0 FILL AAD-N @ IF $59 ELSE $19 THEN MAC C!
  NONCE MAC 1+ 13 MOVE PAY-N @ MAC 14 + BE16!
  MAC AES128-BEGIN 1 STAGE ! ;
: BEGIN-COUNTER ( n stage -- )
  STAGE ! CTR 16 0 FILL 1 CTR C! NONCE CTR 1+ 13 MOVE CTR 14 + BE16!
  CTR AES128-BEGIN ;
: BEGIN-CRYPT ( -- )
  POSITION @ 16 / 1+ 5 BEGIN-COUNTER ;
: BEGIN-AAD ( -- )
  16 0 DO
    POSITION @ I + DUP AAD-N @ 2 + < IF
      DUP 0= IF DROP AAD-N @ 8 RSHIFT ELSE
        DUP 1 = IF DROP AAD-N @ $FF AND ELSE 2 - AAD-A @ + C@ THEN
      THEN
      MAC I + DUP C@ ROT XOR SWAP C!
    ELSE DROP THEN
  LOOP MAC AES128-BEGIN 2 STAGE ! ;
: BEGIN-PAY ( -- )
  PAY-N @ POSITION @ - 16 MIN 0 ?DO
    PAY-A @ POSITION @ + I + C@ MAC I + DUP C@ ROT XOR SWAP C!
  LOOP MAC AES128-BEGIN 3 STAGE ! ;
: BEGIN-MESSAGE ( -- )
  0 POSITION ! PAY-N @ IF BEGIN-PAY ELSE 0 4 BEGIN-COUNTER THEN ;
: FINISH ( -- )
  WIPE 0 BUSY ! 0 STAGE ! 0 POSITION ! 0 DECRYPTING ! ;
: AUTHENTICATED ( -- )
  DECRYPTING @ IF
    0 8 0 DO MAC I + C@ STREAM I + C@ XOR TAG-A @ I + C@ XOR OR LOOP
    IF PAY-A @ PAY-N @ 0 FILL FINISH -411 THROW THEN FINISH
  ELSE
    8 0 DO MAC I + C@ STREAM I + C@ XOR TAG-A @ I + C! LOOP
    0 POSITION ! PAY-N @ IF BEGIN-CRYPT ELSE FINISH THEN
  THEN ;
: BLOCK-DONE ( -- )
  STAGE @ CASE
    1 OF 0 POSITION ! AAD-N @ IF BEGIN-AAD ELSE BEGIN-MESSAGE THEN ENDOF
    2 OF
      16 POSITION +! POSITION @ AAD-N @ 2 + < IF BEGIN-AAD ELSE BEGIN-MESSAGE THEN
    ENDOF
    3 OF
      16 POSITION +! POSITION @ PAY-N @ < IF BEGIN-PAY ELSE 0 4 BEGIN-COUNTER THEN
    ENDOF
    4 OF AUTHENTICATED ENDOF
    5 OF
      PAY-N @ POSITION @ - 16 MIN 0 ?DO
        PAY-A @ POSITION @ + I + DUP C@ STREAM I + C@ XOR SWAP C!
      LOOP
      16 POSITION +! POSITION @ PAY-N @ < IF BEGIN-CRYPT ELSE
        DECRYPTING @ IF BEGIN-AUTH ELSE FINISH THEN
      THEN
    ENDOF
  ENDCASE ;

PUBLIC
: CCM-START ( nonce aad an payload pn tag decrypt? -- )
  BUSY @ ABORT" CCM is busy"
  >R PARAMETERS R> DECRYPTING ! 0 POSITION !
  DECRYPTING @ 0<> PAY-N @ 0<> AND IF BEGIN-CRYPT ELSE BEGIN-AUTH THEN TRUE BUSY ! ;
: CCM-STEP ( -- done )
  BUSY @ 0= ABORT" CCM not started"
  STAGE @ 4 = STAGE @ 5 = OR IF STREAM ELSE MAC THEN 4 AES128-STEP
  IF BLOCK-DONE THEN BUSY @ 0= ;
: CCM-CANCEL ( -- )
  BUSY @ IF PAY-A @ PAY-N @ 0 FILL THEN FINISH ;
: CCM-BUSY? ( -- f ) BUSY @ ;
END-PACKAGE
