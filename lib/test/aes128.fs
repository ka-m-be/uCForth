\ aes128.fs - FIPS 197/RFC 3394; load AES128, BYTES and tester first
ONLY FORTH DEFINITIONS ALSO AES128 ALSO BYTES
CREATE AK $00 C, $01 C, $02 C, $03 C, $04 C, $05 C, $06 C, $07 C,
  $08 C, $09 C, $0A C, $0B C, $0C C, $0D C, $0E C, $0F C,
CREATE AP $00 C, $11 C, $22 C, $33 C, $44 C, $55 C, $66 C, $77 C,
  $88 C, $99 C, $AA C, $BB C, $CC C, $DD C, $EE C, $FF C,
CREATE AC $69 C, $C4 C, $E0 C, $D8 C, $6A C, $7B C, $04 C, $30 C,
  $D8 C, $CD C, $B7 C, $80 C, $70 C, $B4 C, $C5 C, $5A C,
CREATE KW $1F C, $A6 C, $8B C, $0A C, $81 C, $12 C, $B4 C, $47 C,
  $AE C, $F3 C, $4B C, $D8 C, $FB C, $5A C, $7B C, $82 C,
  $9D C, $3E C, $86 C, $23 C, $71 C, $D2 C, $CF C, $E5 C,
32 BUFFER: AB
24 BUFFER: BAD-WRAP
AK AES128-KEY
T{ AP AB AES128-ENCRYPT AB AC 16 BYTES= -> TRUE }T
T{ AC AB AES128-DECRYPT AB AP 16 BYTES= -> TRUE }T
AP AB 16 MOVE
T{ AB AB AES128-ENCRYPT AB AC 16 BYTES= -> TRUE }T
T{ AB AB AES128-DECRYPT AB AP 16 BYTES= -> TRUE }T
T{ KW 24 AB AES128-UNWRAP AB AP 16 BYTES= -> 16 TRUE }T
KW BAD-WRAP 24 MOVE BAD-WRAP DUP C@ 1 XOR SWAP C!
: BAD-KW ( -- )  BAD-WRAP 24 AB AES128-UNWRAP DROP ;
: ZERO-AB? ( -- f )  TRUE 16 0 DO AB I + C@ 0= AND LOOP ;
T{ ' BAD-KW CATCH -> -410 }T
T{ ZERO-AB? -> TRUE }T
: BAD-N ( -- )  KW 23 AB AES128-UNWRAP DROP ;
AB 32 $A5 FILL
T{ ' BAD-N CATCH 0<> AB C@ -> TRUE $A5 }T
AES128-CLEAR
: NO-KEY ( -- )  AP AB AES128-ENCRYPT ;
T{ ' NO-KEY CATCH 0<> -> TRUE }T
AES128-CONTEXT BUFFER: SAVED-AES
AK AES128-KEY SAVED-AES AES128-SAVE AES128-CLEAR
T{ SAVED-AES AES128-RESTORE AP AB AES128-ENCRYPT AB AC 16 BYTES= -> TRUE }T
AP AES128-BEGIN
T{ AB 4 AES128-STEP -> FALSE }T
SAVED-AES AES128-SAVE AES128-CLEAR SAVED-AES AES128-RESTORE
T{ AB 4 AES128-STEP AB 4 AES128-STEP AB AC 16 BYTES= -> FALSE TRUE TRUE }T
AES128-CLEAR
S" aes128" .RESULTS
