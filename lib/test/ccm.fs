  $A0 C, $A1 C, $A2 C, $A3 C, $A4 C, $A5 C,
CREATE CP $08 C, $09 C, $0A C, $0B C, $0C C, $0D C, $0E C, $0F C,
  $10 C, $11 C, $12 C, $13 C, $14 C, $15 C, $16 C, $17 C,
  $18 C, $19 C, $1A C, $1B C, $1C C, $1D C, $1E C,
CREATE CE $58 C, $8C C, $97 C, $9A C, $61 C, $C6 C, $63 C, $D2 C,
  $F0 C, $66 C, $D0 C, $C2 C, $C0 C, $F9 C, $89 C, $80 C,
  $6D C, $5F C, $6B C, $61 C, $DA C, $C3 C, $84 C,
CREATE CT $17 C, $E8 C, $D1 C, $2C C, $FD C, $F9 C, $26 C, $E0 C,
CREATE CA 0 C, 1 C, 2 C, 3 C, 4 C, 5 C, 6 C, 7 C,
23 BUFFER: CB
8 BUFFER: TAG
: ENC ( -- )  CN CA 8 CB 23 TAG CCM-ENCRYPT ;
: DEC ( -- )  CN CA 8 CB 23 TAG CCM-DECRYPT ;
: LOAD-P ( -- )  CP CB 23 MOVE CK AES128-KEY ;
: LOAD-C ( -- )  CE CB 23 MOVE CT TAG 8 MOVE CK AES128-KEY ;
: ZERO-P? ( -- f )  TRUE 23 0 DO CB I + C@ 0= AND LOOP ;
LOAD-P
T{ ENC CB CE 23 BYTES= TAG CT 8 BYTES= -> TRUE TRUE }T
T{ DEC CB CP 23 BYTES= -> TRUE }T
LOAD-C TAG DUP C@ 1 XOR SWAP C!
T{ ' DEC CATCH -> -411 }T
T{ ZERO-P? -> TRUE }T
LOAD-C CB 12 + DUP C@ 1 XOR SWAP C!
T{ ' DEC CATCH -> -411 }T
T{ ZERO-P? -> TRUE }T
LOAD-C CA DUP C@ 1 XOR SWAP C!
T{ ' DEC CATCH -> -411 }T
T{ ZERO-P? -> TRUE }T
CA DUP C@ 1 XOR SWAP C!
: BAD-PAY ( -- )  CN CA 8 CB -1 TAG CCM-ENCRYPT ;
CB 23 $A5 FILL
T{ ' BAD-PAY CATCH 0<> CB C@ -> TRUE $A5 }T
CREATE EMPTY-TAG $F4 C, $81 C, $22 C, $03 C, $4D C, $40 C, $C8 C, $98 C,
CREATE NOAAD $50 C, $84 C, $9F C, $92 C, $69 C, $CE C, $6B C, $DA C,
  $E8 C, $7E C, $C8 C, $DA C, $D8 C, $E1 C, $91 C, $98 C,
CREATE NOAAD-TAG $13 C, $AC C, $45 C, $BE C, $68 C, $7D C, $C8 C, $B7 C,
: EMPTY-ENC ( -- )  CN 0 0 CB 0 TAG CCM-ENCRYPT ;
: EMPTY-DEC ( -- )  CN 0 0 CB 0 TAG CCM-DECRYPT ;
T{ EMPTY-ENC TAG EMPTY-TAG 8 BYTES= -> TRUE }T
T{ EMPTY-DEC -> }T
: INIT-NOAAD ( -- )  16 0 DO I CB I + C! LOOP ;
INIT-NOAAD
T{ CN 0 0 CB 16 TAG CCM-ENCRYPT CB NOAAD 16 BYTES= TAG NOAAD-TAG 8 BYTES= -> TRUE TRUE }T
T{ CN 0 0 CB 16 TAG CCM-DECRYPT CB C@ CB 15 + C@ -> 0 15 }T
: BAD-AAD ( -- )  CN CA 65280 CB 16 TAG CCM-ENCRYPT ;
T{ ' BAD-AAD CATCH 0<> CB 15 + C@ -> TRUE 15 }T
: COMPLETE-CCM ( -- ) BEGIN CCM-STEP UNTIL ;
LOAD-P
T{ CN CA 8 CB 23 TAG FALSE CCM-START CCM-BUSY? -> TRUE }T
T{ COMPLETE-CCM CB CE 23 BYTES= TAG CT 8 BYTES= CCM-BUSY? -> TRUE TRUE FALSE }T
LOAD-C
T{ CN CA 8 CB 23 TAG TRUE CCM-START COMPLETE-CCM CB CP 23 BYTES= -> TRUE }T
LOAD-C TAG DUP C@ 1 XOR SWAP C!
CN CA 8 CB 23 TAG TRUE CCM-START
T{ ' COMPLETE-CCM CATCH ZERO-P? CCM-BUSY? -> -411 TRUE FALSE }T
LOAD-P CN CA 8 CB 23 TAG FALSE CCM-START CCM-CANCEL
T{ ZERO-P? CCM-BUSY? -> TRUE FALSE }T
AES128-CLEAR
