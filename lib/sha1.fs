\ sha1.fs - SHA-1 (FIPS 180-4), for protocol compatibility, not new signatures
PACKAGE SHA1
: NEED-32 ( -- )  CELL 4 <> ABORT" SHA1 needs 32-bit cells" ;  NEED-32

96 BUFFER: CTX
CTX 20 + CONSTANT LO
CTX 24 + CONSTANT HI
CTX 28 + CONSTANT USED
CTX 32 + CONSTANT BLOCK
16 CELLS BUFFER: W
5 CELLS BUFFER: V
20 BUFFER: DIGEST
CREATE INITIAL  $67452301 , $EFCDAB89 , $98BADCFE , $10325476 , $C3D2E1F0 ,

: BE@ ( a -- x )
  DUP C@ 24 LSHIFT OVER 1+ C@ 16 LSHIFT OR OVER 2 + C@ 8 LSHIFT OR SWAP 3 + C@ OR ;
: BE! ( x a -- )
  OVER 24 RSHIFT OVER C! OVER 16 RSHIFT OVER 1+ C! OVER 8 RSHIFT OVER 2 + C! 3 + C! ;
: ROL ( x n -- x' )  2DUP LSHIFT >R 32 SWAP - RSHIFT R> OR ;
: WADDR ( i -- a )  15 AND CELLS W + ;
: V@ ( i -- x )  CELLS V + @ ;
: ROUND-F ( i -- f k )
  DUP 20 < IF DROP 1 V@ 2 V@ AND 1 V@ INVERT 3 V@ AND OR $5A827999 EXIT THEN
  DUP 40 < IF DROP 1 V@ 2 V@ 3 V@ XOR XOR $6ED9EBA1 EXIT THEN
  60 < IF 1 V@ 2 V@ AND 1 V@ 3 V@ AND OR 2 V@ 3 V@ AND OR $8F1BBCDC
  ELSE 1 V@ 2 V@ 3 V@ XOR XOR $CA62C1D6 THEN ;
: COMPRESS ( -- )
  16 0 DO BLOCK I 4 * + BE@ I WADDR ! LOOP
  CTX V 20 MOVE
  80 0 DO
    I 16 < 0= IF
      I 3 - WADDR @ I 8 - WADDR @ XOR I 14 - WADDR @ XOR I WADDR @ XOR
      1 ROL I WADDR !
    THEN
    I ROUND-F + 0 V@ 5 ROL + 4 V@ + I WADDR @ +
    V V CELL+ 4 CELLS MOVE  V !  2 V@ 30 ROL V 2 CELLS + !
  LOOP
  5 0 DO I V@ I CELLS CTX + +! LOOP 0 USED ! ;
: BYTE ( c -- )
  BLOCK USED @ + C! 1 USED +! USED @ 64 = IF COMPRESS THEN ;

PUBLIC
96 CONSTANT SHA1-CONTEXT
: SHA1-SAVE ( a -- )  CTX SWAP SHA1-CONTEXT MOVE ;
: SHA1-RESTORE ( a -- )  CTX SHA1-CONTEXT MOVE ;
: SHA1-START ( -- )  CTX SHA1-CONTEXT 0 FILL INITIAL CTX 20 MOVE ;
: SHA1-ADD ( a u -- )
  DUP 0< ABORT" negative SHA1 length"
  DUP LO @ + DUP LO @ U< IF 1 HI +! THEN LO !
  0 ?DO DUP C@ BYTE 1+ LOOP DROP ;
: SHA1-END ( -- a )
  $80 BYTE BEGIN USED @ 56 <> WHILE 0 BYTE REPEAT
  HI @ 3 LSHIFT LO @ 29 RSHIFT OR BLOCK 56 + BE!
  LO @ 3 LSHIFT BLOCK 60 + BE! COMPRESS
  5 0 DO I CELLS CTX + @ DIGEST I 4 * + BE! LOOP DIGEST ;
: SHA1-DIGEST ( a u -- a' )  SHA1-START SHA1-ADD SHA1-END ;
: SHA1-CLEAR ( -- )
  CTX SHA1-CONTEXT 0 FILL W 16 CELLS 0 FILL V 20 0 FILL DIGEST 20 0 FILL ;
END-PACKAGE
