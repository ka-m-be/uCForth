\ kdf1.fs - HMAC-SHA1, bounded PBKDF2 and the SHA1 PRF used by WPA2
\ Load SHA1 first. One caller at a time; never call from an interrupt.
PACKAGE KDF1  ALSO SHA1
64 BUFFER: PAD
SHA1-CONTEXT BUFFER: INNER
SHA1-CONTEXT BUFFER: OUTER
VARIABLE HREADY
: PREPARE ( key n inner outer -- )
  >R >R DUP 0< ABORT" negative HMAC key length"
  DUP 64 > IF SHA1-DIGEST 20 THEN
  PAD 64 0 FILL PAD SWAP MOVE
  64 0 DO PAD I + DUP C@ $36 XOR SWAP C! LOOP
  SHA1-START PAD 64 SHA1-ADD R> SHA1-SAVE
  64 0 DO PAD I + DUP C@ $36 $5C XOR XOR SWAP C! LOOP
  SHA1-START PAD 64 SHA1-ADD R> SHA1-SAVE PAD 64 0 FILL ;
: FINISH ( outer -- a )
  SHA1-END SWAP SHA1-RESTORE 20 SHA1-ADD SHA1-END ;
: HASH-KEYED ( a n inner outer -- digest )
  >R SHA1-RESTORE SHA1-ADD R> FINISH ;

PUBLIC
: HMAC1-START ( key n -- )
  INNER OUTER PREPARE INNER SHA1-RESTORE TRUE HREADY ! ;
: HMAC1-ADD ( a n -- )
  HREADY @ 0= ABORT" HMAC1 not started" SHA1-ADD ;
: HMAC1-END ( -- a )
  HREADY @ 0= ABORT" HMAC1 not started" 0 HREADY ! OUTER FINISH ;
: HMAC1-DIGEST ( key n a u -- digest )
  >R >R HMAC1-START R> R> HMAC1-ADD HMAC1-END ;
: HMAC1-CLEAR ( -- )
  INNER SHA1-CONTEXT 0 FILL OUTER SHA1-CONTEXT 0 FILL 0 HREADY ! SHA1-CLEAR ;

PRIVATE
SHA1-CONTEXT BUFFER: PINNER
SHA1-CONTEXT BUFFER: POUTER
64 BUFFER: SALT
20 BUFFER: U
20 BUFFER: T
4 BUFFER: INDEX
VARIABLE SLEN  VARIABLE ROUNDS  VARIABLE ROUND
VARIABLE BLOCKNO  VARIABLE DEST  VARIABLE LEFT
VARIABLE ORIGINAL  VARIABLE DLEN
VARIABLE PSTATE                    \ 0 idle, 1 working, 2 complete
: WIPE-P ( -- )
  PINNER SHA1-CONTEXT 0 FILL POUTER SHA1-CONTEXT 0 FILL
  SALT 64 0 FILL U 20 0 FILL T 20 0 FILL INDEX 4 0 FILL
  0 SLEN ! 0 ROUNDS ! 0 ROUND ! 0 BLOCKNO ! SHA1-CLEAR ;
: ONE-ROUND ( -- )
  ROUND @ 0= IF
    BLOCKNO @ INDEX 4 + 4 0 DO 1- OVER $FF AND OVER C! SWAP 8 RSHIFT SWAP LOOP 2DROP
    PINNER SHA1-RESTORE SALT SLEN @ SHA1-ADD INDEX 4 SHA1-ADD POUTER FINISH
    DUP U 20 MOVE T 20 MOVE
  ELSE
    U 20 PINNER POUTER HASH-KEYED U 20 MOVE
    20 0 DO T I + DUP C@ U I + C@ XOR SWAP C! LOOP
  THEN
  1 ROUND +!
  ROUND @ ROUNDS @ = IF
    LEFT @ 20 MIN >R T DEST @ R@ MOVE
    R@ DEST +! R> NEGATE LEFT +! 1 BLOCKNO +! 0 ROUND !
    LEFT @ 0= IF WIPE-P 2 PSTATE ! THEN
  THEN ;

PUBLIC
: PBKDF2-START ( key kn salt sn count out n -- )
  PSTATE @ 1 = ABORT" PBKDF2 already running"
  DUP 1 65536 WITHIN 0= ABORT" bad PBKDF2 output length"
  >R >R DUP 1 < ABORT" PBKDF2 count must be positive"
  >R DUP 0 65 WITHIN 0= ABORT" PBKDF2 salt exceeds 64 bytes"
  >R >R DUP 0< ABORT" negative PBKDF2 key length"
  PINNER POUTER PREPARE R> R> DUP SLEN ! SALT SWAP MOVE
  R> ROUNDS ! R> DUP ORIGINAL ! DEST ! R> DUP DLEN ! LEFT !
  ORIGINAL @ DLEN @ 0 FILL 0 ROUND ! 1 BLOCKNO ! 1 PSTATE ! ;
: PBKDF2-STEP ( budget -- done )
  DUP 1 < ABORT" PBKDF2 budget must be positive"
  PSTATE @ 0= ABORT" PBKDF2 not started"
  8 MIN 0 DO PSTATE @ 1 = IF ONE-ROUND THEN LOOP PSTATE @ 2 = ;
: PBKDF2-CANCEL ( -- )
  PSTATE @ 1 = IF ORIGINAL @ DLEN @ 0 FILL THEN
  WIPE-P 0 DEST ! 0 ORIGINAL ! 0 DLEN ! 0 LEFT ! 0 PSTATE ! ;
: PBKDF2 ( key kn salt sn count out n -- )
  PBKDF2-START BEGIN 16 PBKDF2-STEP UNTIL ;

PRIVATE
SHA1-CONTEXT BUFFER: RINNER
SHA1-CONTEXT BUFFER: ROUTER
VARIABLE LABEL-A  VARIABLE LABEL-N
VARIABLE DATA-A   VARIABLE DATA-N
VARIABLE PRF-OUT  VARIABLE PRF-LEFT
CREATE SEP 0 C,
1 BUFFER: COUNTER

PUBLIC
: SHA1-PRF ( key kn label ln data dn out n -- )
  DUP 1 5121 WITHIN 0= ABORT" bad PRF output length"
  >R >R DUP 0< ABORT" negative PRF data length"
  >R >R DUP 0< ABORT" negative PRF label length"
  >R >R DUP 0< ABORT" negative PRF key length"
  RINNER ROUTER PREPARE
  R> LABEL-A ! R> LABEL-N ! R> DATA-A ! R> DATA-N ! R> PRF-OUT ! R> PRF-LEFT ! 0 COUNTER C!
  BEGIN
    RINNER SHA1-RESTORE LABEL-A @ LABEL-N @ SHA1-ADD SEP 1 SHA1-ADD
    DATA-A @ DATA-N @ SHA1-ADD COUNTER 1 SHA1-ADD ROUTER FINISH
    PRF-LEFT @ 20 MIN DUP >R PRF-OUT @ SWAP MOVE
    R@ PRF-OUT +! R> NEGATE PRF-LEFT +!
    COUNTER DUP C@ 1+ SWAP C! PRF-LEFT @ 0=
  UNTIL
  RINNER SHA1-CONTEXT 0 FILL ROUTER SHA1-CONTEXT 0 FILL SHA1-CLEAR ;
END-PACKAGE
