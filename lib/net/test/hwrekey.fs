\ hwrekey.fs - a protected group update through WIFI-LINK with hardware CCMP (synthetic keys)
ONLY FORTH DEFINITIONS ALSO FILES
[DEFINED] TEST-STA S" lib/net/test/wpasta.fs" ?INCLUDED
ONLY FORTH DEFINITIONS ALSO FILES
[DEFINED] RUN-TICKS S" lib/net/test/wlink.fs" ?INCLUDED
ONLY FORTH DEFINITIONS ALSO FILES
[DEFINED] HW-TICKS S" lib/net/test/hwlink.fs" ?INCLUDED
ONLY FORTH DEFINITIONS ALSO FILES
[DEFINED] GROUP1 S" lib/net/test/rekey.fs" ?INCLUDED
ONLY FORTH DEFINITIONS ALSO BYTES ALSO AES128 ALSO AES128.I ALSO KDF1
ALSO TEST-STA ALSO WLAN ALSO WLAN.I ALSO WIFI-LINK ALSO WIFI-LINK.I
ALSO CCMP
6 BUFFER: TEST-PN
128 BUFFER: G2
: PROTECTED-GROUP ( -- )
  GROUP1 RF 24 + RF 32 + 147 MOVE
  $42 RF 1+ C! TEST-PN 6 0 FILL 1 TEST-PN C!
  TEST-PN RF 24 + 0 CCMP-PN!
  AIR-DECRYPTED ON! 179 RECEIVE ;
: G2-MIC? ( -- f )   \ the MIC of the group message 2 on the air, with the key of the pair
  AIR-TX 40 + G2 99 MOVE  G2 81 + 16 0 FILL
  STA-PTK 16 G2 99 HMAC1-DIGEST AIR-TX 121 + 16 BYTES=  HMAC1-CLEAR ;
FULL 0 G-LENGTH ! 3 G-REPLAY !
TEST-POOL WLINK-POOL! WLINK-START  0 TX-GOOD !
T{ PROTECTED-GROUP HW-TICKS CONTROL-N @ -> 171 }T
T{ SENDS @ LINK-CONTROL SENDS @ - WIFI-STATUS WIFI-ERROR STA-GID @ STA-GKEYS 32 + C@ -> 0 6 0 2 $5A }T
\ Group message 2 goes protected, through the queue of WIFI-LINK: the AP takes it only so.
T{ HW-TICKS TX-GOOD @ AIR-N @ AIR-TX 1+ C@ AIR-TX 38 + STA-BE@ -> 1 147 $41 $888E }T
T{ AIR-TX 45 + STA-BE@ AIR-TX 56 + C@ G2-MIC? -> $302 3 TRUE }T
STA-GGEN 2 CELLS + @ OLD-GENERATION !
0 OLD !
T{ PROTECTED-GROUP HW-TICKS ERROR @ OLD @ -> 0 1 }T
WLINK-STOP WLINK-START
T{ PROTECTED-GROUP HW-TICKS LINK-CONTROL STA-GGEN 2 CELLS + @ OLD-GENERATION @ = -> TRUE }T
\ A full queue: the answer takes the place of the newest frame, which goes.
WLINK-STOP WLINK-START  0 TX-GOOD !  0 DROPPED !
T{ ETH 30 LINK-SEND ETH 30 LINK-SEND PROTECTED-GROUP HW-TICKS JOB @ CONTROL-N @ -> 0 0 4 171 }T
T{ LINK-CONTROL TX-W @ TX-R @ - DROPPED @ ERROR @ -> 2 1 -441 }T
T{ HW-TICKS TX-GOOD @ AIR-N @ G2-MIC? -> 2 147 TRUE }T
WLINK-STOP WIFI-LEAVE
S" hwrekey" .RESULTS
