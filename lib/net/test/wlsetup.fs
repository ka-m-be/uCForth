CREATE INPUT-TEXT 112 C, 97 C, 115 C, 115 C, 119 C, 111 C, 114 C, 100 C, 13 C,
VARIABLE INPUT-POS VARIABLE INTERRUPT-AT VARIABLE KEY-SAVED
: INPUT-KEY ( -- c true | false )
  INPUT-POS @ INTERRUPT-AT @ = IF -56 THROW THEN
  INPUT-POS @ 9 < 0= IF FALSE EXIT THEN
  INPUT-TEXT INPUT-POS @ + C@ 1 INPUT-POS +! TRUE ;
: FAKE-CONSOLE ( -- )
  'KEY? @ KEY-SAVED ! ['] INPUT-KEY 'KEY? ! -1 KEYBUF ! 0 INPUT-POS ! -1 INTERRUPT-AT ! ;
: RESTORE-CONSOLE ( -- ) KEY-SAVED @ 'KEY? ! -1 KEYBUF ! ;
: PASSWORD-ZERO? ( -- f ) TRUE 64 0 DO PASSWORD I + C@ 0= AND LOOP ;
: INPUT-PROFILE ( -- ) 0 WLAN-PASSWORD ;
: NORMAL-INPUT ( -- )
  1 ECHO ! FAKE-CONSOLE ['] INPUT-PROFILE CATCH RESTORE-CONSOLE THROW ;
: BROKEN-INPUT ( -- ior )
  WIFI-LEAVE FAKE-CONSOLE 3 INTERRUPT-AT ! ['] INPUT-PROFILE CATCH RESTORE-CONSOLE ;
T{ NORMAL-INPUT WIFI-STATUS PASSWORD-ZERO? ECHO @ NO-BREAK @ -> 1 TRUE 1 0 }T
T{ BROKEN-INPUT PASSWORD-ZERO? ECHO @ NO-BREAK @ WIFI-STATUS -> -56 TRUE 1 0 0 }T
0 ECHO !
