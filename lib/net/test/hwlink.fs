[DEFINED] TEST-STA S" lib/net/test/wpasta.fs" ?INCLUDED
ONLY FORTH DEFINITIONS ALSO FILES
[DEFINED] RUN-TICKS S" lib/net/test/wlink.fs" ?INCLUDED
ONLY FORTH DEFINITIONS ALSO TEST-STA
TEST-STA DEFINITIONS
VARIABLE AIR-DECRYPTED
: RADIO-CCMP? ( -- f ) TRUE ;
: RADIO-DECRYPTED? ( -- f ) AIR-DECRYPTED @ ;
ONLY FORTH DEFINITIONS ALSO FILES
INCLUDE lib/net/wlink.fs
ONLY FORTH DEFINITIONS ALSO BYTES ALSO TEST-STA ALSO WLAN ALSO WLAN.I ALSO WIFI-LINK ALSO WIFI-LINK.I
: RX-HW ( -- )
  RF 56 0 FILL RX-FIXTURE RF 32 MOVE
  $AA RF 32 + C! $AA RF 33 + C! 3 RF 34 + C! 8 RF 38 + C!
  16 0 DO I RF 40 + I + C! LOOP TRUE AIR-DECRYPTED ! 56 RECEIVE ;
: HW-TICKS ( -- ) 20 0 DO LINK-TICK LOOP ;

FULL FALSE RF-READY ! TEST-POOL WLINK-POOL! WLINK-START BUILD-ETH
T{ ETH 30 LINK-SEND HW-TICKS AIR-N @ TX-GOOD @ -> 0 64 1 }T
T{ AIR-TX 32 + C@ AIR-TX 38 + C@ AIR-TX 55 + C@ AIR-TX 56 + @ -> $AA 8 15 0 }T
T{ RX-HW HW-TICKS RECEIVED-ETH LINK-RECEIVE -> 30 }T
T{ RECEIVED-ETH 12 + C@ RECEIVED-ETH 29 + C@ -> 8 15 }T
0 OLD !
T{ RX-HW HW-TICKS RECEIVED-ETH LINK-RECEIVE ERROR @ OLD @ -> 0 0 1 }T
WLINK-STOP WLINK-START
T{ RX-HW FALSE AIR-DECRYPTED ! HW-TICKS RECEIVED-ETH LINK-RECEIVE ERROR @ -> 0 -411 }T
T{ RX-HW HW-TICKS RECEIVED-ETH LINK-RECEIVE -> 30 }T
WLINK-STOP WLINK-START
RX-HW
LINK-TICK
T{ JOB @ -> 5 }T
1 STA-PGEN +!
0 OLD !
T{ LINK-TICK RAW-R @ TX-R @ ERROR @ OLD @ -> 1 0 0 1 }T
WLINK-STOP WLINK-START
RF 26 0 FILL $C8 RF C! 2 RF 1+ C! 26 RECEIVE
T{ HW-TICKS WIFI-STATUS ERROR @ CONTROL-N @ -> 6 0 0 }T
WLINK-STOP WIFI-LEAVE
S" hwlink" .RESULTS
