\ rekey.fs - WLAN: a new group key, and the same group message twice (synthetic keys)
ONLY FORTH DEFINITIONS ALSO FILES
[DEFINED] TEST-STA S" lib/net/test/wpasta.fs" ?INCLUDED
ONLY FORTH DEFINITIONS ALSO AES128 ALSO AES128.I ALSO BYTES ALSO KDF1
ALSO TEST-STA ALSO WLAN ALSO WLAN.I
32 BUFFER: GROUP-DATA
40 BUFFER: WRAPPED
VARIABLE G-REPLAY
VARIABLE OLD-GENERATION
VARIABLE G-LENGTH
16 G-LENGTH !
: WRAP-GROUP ( -- )
  WRAPPED 8 $A6 FILL GROUP-DATA WRAPPED 8 + 32 MOVE
  STA-PTK 16 + AES128-KEY
  6 0 DO 4 0 DO
    WRAPPED WRAP-B 8 MOVE WRAPPED I 1+ 8 * + WRAP-B 8 + 8 MOVE
    WRAP-B WRAP-B AES128-ENCRYPT J 4 * I 1+ + XOR-T
    WRAP-B WRAPPED 8 MOVE WRAP-B 8 + WRAPPED I 1+ 8 * + 8 MOVE
  LOOP LOOP ;
: GROUP1 ( -- )
  GROUP-DATA 32 0 FILL $DD GROUP-DATA C! 22 GROUP-DATA 1+ C!
  STA-GTK-TYPE GROUP-DATA 2 + 4 MOVE 2 GROUP-DATA 6 + C!
  GROUP-DATA 8 + 16 $5A FILL $DD GROUP-DATA 24 + C!
  WRAP-GROUP
  8 2 RF-HEADER STA-LLC RF 24 + 8 MOVE
  2 RF 32 + C! 3 RF 33 + C! 135 RF 34 + STA-BE!
  2 RF 36 + C! $1382 RF 37 + STA-BE! G-LENGTH @ RF 39 + STA-BE!
  G-REPLAY @ RF 48 + C! 40 RF 129 + STA-BE! WRAPPED RF 131 + 40 MOVE
  STA-PTK 16 RF 32 + 139 HMAC1-DIGEST RF 113 + 16 MOVE HMAC1-CLEAR
  171 RECEIVE ;
FULL 3 G-REPLAY !
T{ GROUP1 WIFI-POLL WIFI-STATUS WIFI-ERROR STA-GID @ STA-GKEYS 32 + C@ -> 6 0 2 $5A }T
\ Without a running link, group message 2 goes plain, over the radio.
T{ SENT-N @ SENT 1+ C@ SENT 37 + STA-BE@ SENT 48 + C@ -> 131 1 $302 3 }T
FULL 0 G-LENGTH !
T{ GROUP1 WIFI-POLL WIFI-STATUS WIFI-ERROR STA-GID @ -> 6 0 2 }T
T{ GROUP1 179 RECEIVE WIFI-POLL WIFI-STATUS WIFI-ERROR -> 6 0 }T
STA-GGEN 2 CELLS + @ OLD-GENERATION !
9 STA-TXPN C! 7 STA-GRSCS 12 + C!
T{ GROUP1 WIFI-POLL STA-GGEN 2 CELLS + @ OLD-GENERATION @ = STA-TXPN C@ STA-GRSCS 12 + C@ -> TRUE 9 7 }T
2 G-REPLAY !
T{ GROUP1 WIFI-POLL WIFI-STATUS WIFI-ERROR -> 7 -425 }T
FULL 3 G-REPLAY !
GROUP1 RF 113 + DUP C@ 1 XOR SWAP C!
T{ WIFI-POLL WIFI-STATUS WIFI-ERROR ZERO-KEYS? -> 7 -421 TRUE }T
TO-M3 FEED3 0 RF 39 + STA-BE! REMIC3
T{ WIFI-POLL WIFI-STATUS WIFI-ERROR -> 7 -426 }T
WIFI-LEAVE
