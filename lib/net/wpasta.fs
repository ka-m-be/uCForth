VARIABLE STA-ELEN VARIABLE STA-M3LEN VARIABLE STA-GID
VARIABLE STA-INSTALLED VARIABLE STA-INSTALLS
VARIABLE STA-SINCE VARIABLE STA-RETRIES VARIABLE STA-SEQUENCE VARIABLE STA-SENDS
