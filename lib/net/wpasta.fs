CREATE STA-LLC $AA C, $AA C, 3 C, 0 C, 0 C, 0 C, $88 C, $8E C,
CREATE STA-RATES 1 C, 8 C, $82 C, $84 C, $8B C, $96 C, 12 C, 18 C, 24 C, 36 C,
  50 C, 4 C, 48 C, 72 C, 96 C, 108 C,
CREATE STA-OUR-RSN 48 C, 20 C, 1 C, 0 C, 0 C, $0F C, $AC C, 4 C,
  1 C, 0 C, 0 C, $0F C, $AC C, 4 C, 1 C, 0 C, 0 C, $0F C, $AC C, 2 C, 0 C, 0 C,
CREATE STA-GTK-TYPE 0 C, $0F C, $AC C, 1 C,
: STA-LE@ ( a -- u ) DUP C@ SWAP 1+ C@ 8 LSHIFT OR ;
: STA-BE@ ( a -- u ) DUP C@ 8 LSHIFT SWAP 1+ C@ OR ;
: STA-LE! ( x a -- ) OVER OVER C! SWAP 8 RSHIFT SWAP 1+ C! ;
: STA-BE! ( x a -- ) OVER 8 RSHIFT OVER C! 1+ C! ;
: STA-NEED ( f -- ) 0= IF -426 THROW THEN ;
: STA-KEYS-CLEAR ( -- )
  STA-PTK 64 0 FILL STA-GTK 16 0 FILL STA-GRSC 6 0 FILL
  STA-TXPN 6 0 FILL STA-RXPN 6 0 FILL STA-ANONCE 32 0 FILL STA-SNONCE 32 0 FILL
  STA-EAP 400 0 FILL STA-M3 400 0 FILL STA-G1 400 0 FILL
  0 STA-G1LEN ! 0 STA-GROUP-MODE ! STA-KDATA 256 0 FILL STA-MIC 16 0 FILL
  STA-REPLAY 8 0 FILL 0 STA-INSTALLED ! 0 STA-M3LEN ! 0 STA-ELEN ! 0 STA-GID !
  STA-GKEYS 64 0 FILL STA-GRSCS 24 0 FILL 0 STA-GVALID ! 1 STA-PGEN +!
  HMAC1-CLEAR AES128-CLEAR ;
: STA-GTK-INSTALL ( -- )
  STA-GVALID @ 1 STA-GID @ LSHIFT AND IF
    STA-GTK STA-GKEYS STA-GID @ 16 * + 16 BYTES= IF EXIT THEN
  THEN
  STA-GTK STA-GKEYS STA-GID @ 16 * + 16 MOVE
  STA-GRSC STA-GRSCS STA-GID @ 6 * + 6 MOVE
  1 STA-GID @ CELLS STA-GGEN + +!
  STA-GVALID @ 1 STA-GID @ LSHIFT OR STA-GVALID ! ;
: STA-FAIL ( ior -- )
  DUP STA-ERROR ! ." WIFI failed at stage " STA-STATE @ . ." code " . CR
  7 STA-STATE ! STA-KEYS-CLEAR STA-PMK 32 0 FILL WPA-PMK-CANCEL ;
: STA-STATE! ( n -- ) STA-STATE ! 0 STA-RETRIES ! MILLIS STA-SINCE ! ;
: STA-DRAIN ( -- )
  8 0 DO RADIO-RECEIVE ?DUP IF 2DROP THEN LOOP ;
: STA-HEADER ( fc flags -- )
  STA-TX 512 0 FILL STA-TX 1+ C! STA-TX C! 60 STA-TX 2 + STA-LE!
  STA-PEER STA-TX 4 + 6 MOVE STA-OWN STA-TX 10 + 6 MOVE STA-PEER STA-TX 16 + 6 MOVE
  STA-SEQUENCE @ $FFF AND 4 LSHIFT STA-TX 22 + STA-LE! 1 STA-SEQUENCE +! ;
: STA-SEND ( n -- )
  STA-SENDS @ 24 < 0= IF DROP -429 THROW THEN
  STA-DRAIN 1 STA-SENDS +! STA-TX SWAP TRUE RADIO-SEND MILLIS STA-SINCE ! ;
: STA-AUTH ( -- ) $B0 0 STA-HEADER 1 STA-TX 26 + STA-LE! 30 STA-SEND ;
: STA-ASSOC ( -- )
  0 0 STA-HEADER
  STA-CAP @ $420 AND $11 OR STA-TX 24 + STA-LE! 10 STA-TX 26 + STA-LE!
  0 STA-TX 28 + C! STA-SLEN @ STA-TX 29 + C! STA-SSID STA-TX 30 + STA-SLEN @ MOVE
  STA-RATES STA-TX 30 + STA-SLEN @ + 16 MOVE
  STA-OUR-RSN STA-TX 46 + STA-SLEN @ + 22 MOVE STA-SLEN @ 68 + STA-SEND ;
: STA-EAP-HEADER ( flags kn -- )
  >R 8 1 STA-HEADER STA-LLC STA-TX 24 + 8 MOVE
  2 STA-TX 32 + C! 3 STA-TX 33 + C! R@ 95 + STA-TX 34 + STA-BE!
  2 STA-TX 36 + C! STA-TX 37 + STA-BE!
  STA-REPLAY STA-TX 41 + 8 MOVE
  R> STA-TX 129 + STA-BE! ;
: STA-TX-MIC ( n -- )
  >R STA-PTK 16 STA-TX 32 + R> HMAC1-DIGEST STA-TX 113 + 16 MOVE HMAC1-CLEAR ;
: STA-M2 ( -- )
  $10A 22 STA-EAP-HEADER STA-SNONCE STA-TX 49 + 32 MOVE
  STA-OUR-RSN STA-TX 131 + 22 MOVE 121 STA-TX-MIC 153 STA-SEND ;
: STA-M4 ( -- )
  $30A 0 STA-EAP-HEADER STA-M3 9 + STA-TX 41 + 8 MOVE 99 STA-TX-MIC 131 STA-SEND ;
: STA-VERIFY-MIC ( -- f )
  STA-EAP 81 + STA-MIC 16 MOVE STA-EAP 81 + 16 0 FILL
  STA-PTK 16 STA-EAP STA-ELEN @ HMAC1-DIGEST STA-MIC 16 BYTES=
  STA-MIC STA-EAP 81 + 16 MOVE HMAC1-CLEAR ;
: STA-NONCE ( -- )
  STA-SNONCE 32 RADIO-RANDOM
  FALSE 7 0 DO STA-SNONCE I 1+ 4 * + @ STA-SNONCE @ <> OR LOOP
  0= IF -427 THROW THEN ;
: STA-M1 ( -- )
  STA-STATE @ 5 = IF
    STA-EAP 9 + STA-REPLAY 8 BYTES= STA-EAP 17 + STA-ANONCE 32 BYTES= AND STA-NEED
    STA-M2 EXIT
  THEN
  STA-STATE @ 4 = STA-NEED
  STA-EAP 9 + STA-REPLAY 8 MOVE STA-EAP 17 + STA-ANONCE 32 MOVE
  STA-NONCE STA-PMK STA-PEER STA-OWN STA-ANONCE STA-SNONCE STA-PTK WPA-PTK
  5 STA-STATE! STA-M2 ;
: STA-KTAKE ( n -- a )
  DUP STA-KN @ > 0= STA-NEED STA-KA @ SWAP DUP NEGATE STA-KN +! STA-KA +! ;
: STA-KDE ( a n -- )
  DUP 4 < IF 2DROP EXIT THEN
  OVER STA-GTK-TYPE 4 BYTES= IF
    22 = STA-NEED STA-HAVE-GTK @ 0= STA-NEED
    DUP 4 + C@ DUP $F8 AND 0= STA-NEED 3 AND STA-GID !
    DUP 5 + C@ 0= STA-NEED 6 + STA-GTK 16 MOVE TRUE STA-HAVE-GTK !
  ELSE 2DROP THEN ;
: STA-KEYDATA ( -- )
  STA-EAP 97 + STA-BE@ DUP 24 265 WITHIN STA-NEED
  STA-PTK 16 + AES128-KEY STA-EAP 99 + SWAP STA-KDATA AES128-UNWRAP STA-KN !
  STA-KDATA STA-KA ! FALSE STA-HAVE-RSN ! FALSE STA-HAVE-GTK !
  BEGIN STA-KN @ WHILE
    2 STA-KTAKE DUP C@ SWAP 1+ C@
    OVER $DD = OVER 0= AND IF
      2DROP BEGIN STA-KN @ WHILE 1 STA-KTAKE C@ 0= STA-NEED REPEAT
    ELSE
      DUP STA-KTAKE SWAP ROT
      DUP 48 = IF
        DROP STA-HAVE-RSN @ 0= STA-NEED
        DUP STA-RLEN @ = STA-NEED STA-RSN SWAP BYTES= STA-NEED TRUE STA-HAVE-RSN !
      ELSE
        $DD = IF STA-KDE ELSE 2DROP THEN
      THEN
    THEN
  REPEAT
  STA-HAVE-GTK @ STA-GROUP-MODE @ 0= IF STA-HAVE-RSN @ AND THEN STA-NEED
  STA-EAP 71 + C@ STA-EAP 72 + C@ OR 0= STA-NEED
  STA-EAP 65 + STA-GRSC 6 MOVE
  STA-KDATA 256 0 FILL AES128-CLEAR ;
: STA-MESSAGE3 ( -- )
  STA-STATE @ DUP 5 = SWAP 6 = OR STA-NEED
  STA-EAP 17 + STA-ANONCE 32 BYTES= STA-NEED
  STA-VERIFY-MIC 0= IF -421 THROW THEN
  STA-INSTALLED @ IF
    STA-ELEN @ STA-M3LEN @ = STA-EAP STA-M3 STA-ELEN @ BYTES= AND
    0= IF -425 THROW THEN STA-M4 EXIT
  THEN
  STA-REPLAY STA-EAP 9 + 8 BYTES< 0= IF -425 THROW THEN
  0 STA-GROUP-MODE ! STA-KEYDATA
  STA-EAP STA-M3 STA-ELEN @ MOVE STA-ELEN @ STA-M3LEN !
  STA-EAP 9 + STA-REPLAY 8 MOVE
  STA-TXPN 6 0 FILL 1 STA-TXPN C! STA-RXPN 6 0 FILL
  1 STA-PGEN +! STA-GTK-INSTALL
  TRUE STA-INSTALLED ! 1 STA-INSTALLS +! STA-M4 6 STA-STATE! ;
: STA-GROUP-REPLY ( -- )
  $302 0 STA-EAP-HEADER STA-G1 9 + STA-TX 41 + 8 MOVE
  99 STA-TX-MIC 131 STA-SEND ;
: STA-GROUP1 ( -- )
  STA-STATE @ 6 = STA-NEED STA-VERIFY-MIC 0= IF -421 THROW THEN
  STA-G1LEN @ STA-ELEN @ = IF
    STA-G1 STA-EAP STA-ELEN @ BYTES= IF STA-GROUP-REPLY EXIT THEN
  THEN
  STA-REPLAY STA-EAP 9 + 8 BYTES< 0= IF -425 THROW THEN
  1 STA-GROUP-MODE ! STA-KEYDATA 0 STA-GROUP-MODE ! STA-GTK-INSTALL
  STA-EAP STA-G1 STA-ELEN @ MOVE STA-ELEN @ STA-G1LEN !
  STA-EAP 9 + STA-REPLAY 8 MOVE
  0 STA-SENDS ! STA-GROUP-REPLY ;
: STA-EAPOL ( a n -- )
  DUP 99 401 WITHIN STA-NEED
  OVER C@ DUP 1 = SWAP 2 = OR STA-NEED OVER 1+ C@ 3 = STA-NEED
  OVER 2 + STA-BE@ 4 + OVER = STA-NEED
  OVER 4 + C@ 2 = STA-NEED
  OVER 97 + STA-BE@ 99 + OVER = STA-NEED
  DUP STA-ELEN ! STA-EAP SWAP MOVE
  STA-EAP 7 + STA-BE@ 16 = STA-NEED
  STA-EAP 5 + STA-BE@ DUP $8A = IF DROP STA-M1 EXIT THEN
  DUP $1382 = OVER $13C2 = OR IF DROP STA-GROUP1 EXIT THEN
  $13CA = STA-NEED STA-MESSAGE3 ;
: STA-OWN-FRAME? ( a n -- f )
  DUP 24 < IF 2DROP FALSE EXIT THEN DROP
  DUP 4 + STA-OWN 6 BYTES= OVER 10 + STA-PEER 6 BYTES= AND
  OVER C@ 12 AND 0= IF OVER 16 + STA-PEER 6 BYTES= AND THEN NIP ;
: STA-DATA ( a n -- )
  OVER 1+ C@ $43 AND 2 <> IF 2DROP EXIT THEN
  OVER 22 + STA-LE@ 15 AND 0= STA-NEED
  OVER C@ DUP 8 = SWAP $88 = OR STA-NEED
  OVER C@ $80 AND IF
    DUP 26 < 0= STA-NEED OVER 24 + C@ $80 AND 0= STA-NEED 26
  ELSE 24 THEN
  OVER OVER 8 + < 0= STA-NEED
  >R R@ - SWAP R> + SWAP
  OVER STA-LLC 8 BYTES= IF 8 - SWAP 8 + SWAP STA-EAPOL ELSE 2DROP THEN ;
: STA-RX ( a n -- )
  2DUP STA-OWN-FRAME? 0= IF 2DROP EXIT THEN
  OVER C@ DUP $B0 = IF
    DROP STA-STATE @ 2 = IF
      DUP 30 < 0= STA-NEED OVER 16 + STA-PEER 6 BYTES= STA-NEED
      OVER 24 + STA-LE@ 0= STA-NEED OVER 26 + STA-LE@ 2 = STA-NEED
      OVER 28 + STA-LE@ IF -423 THROW THEN 2DROP 3 STA-STATE! STA-ASSOC
    ELSE 2DROP THEN EXIT
  THEN
  DUP $10 = IF
    DROP STA-STATE @ 3 = IF
      DUP 30 < 0= STA-NEED OVER 16 + STA-PEER 6 BYTES= STA-NEED
      OVER 26 + STA-LE@ IF -423 THROW THEN
      OVER 28 + STA-LE@ $3FFF AND DUP 1 2008 WITHIN STA-NEED STA-AID ! 4 STA-STATE!
    THEN 2DROP EXIT
  THEN
  DUP $A0 = OVER $C0 = OR IF DROP 2DROP -428 THROW THEN
  12 AND 8 = IF STA-DATA ELSE 2DROP THEN ;
: STA-BEGIN ( -- )
  STA-CHAN @ RADIO-CHANNEL! STA-PEER RADIO-STATION STA-DRAIN 2 STA-STATE! STA-AUTH ;
: STA-TIMEOUT ( -- )
  STA-STATE @ DUP 2 = OVER 3 = OR IF
    MILLIS STA-SINCE @ - 500 < IF DROP EXIT THEN
    STA-RETRIES @ 3 < 0= IF DROP -422 THROW THEN 1 STA-RETRIES +!
    2 = IF STA-AUTH ELSE STA-ASSOC THEN EXIT
  THEN
  DUP 4 = IF DROP MILLIS STA-SINCE @ - 5000 < 0= IF -422 THROW THEN EXIT THEN
  5 = IF
    MILLIS STA-SINCE @ - 1500 < IF EXIT THEN
    STA-RETRIES @ 3 < 0= IF -422 THROW THEN 1 STA-RETRIES +! STA-M2
  THEN ;
: (STA-POLL) ( -- )
  STA-STATE @ 1 = IF
    STA-DRAIN 8 WPA-PMK-STEP IF STA-BEGIN THEN EXIT
  THEN
  STA-STATE @ 2 7 WITHIN IF
    RADIO-RECEIVE ?DUP IF STA-RX THEN STA-TIMEOUT
  THEN ;
: STA-SELECT ( i -- )
  STA-STATE @ 0<> ABORT" WIFI: leave before starting another join"
  DUP WIFI-WPA2? 0= ABORT" WIFI: WPA2-PSK/CCMP without required PMF needed"
  DUP WIFI-PEER STA-PEER 6 MOVE DUP WIFI-RSN STA-CAP !
  DUP STA-RLEN ! STA-RSN SWAP MOVE WIFI-NET DROP STA-CHAN !
  DUP STA-SLEN ! STA-SSID SWAP MOVE RADIO-MAC@ STA-OWN 6 MOVE
  0 STA-ERROR ! 0 STA-SENDS ! 0 STA-INSTALLS ! STA-KEYS-CLEAR ;
: STA-RESULT ( ior -- )
  ?DUP IF
    DUP -2 = OVER -410 = OR OVER -429 -420 WITHIN OR IF STA-FAIL
    ELSE DUP STA-FAIL THROW THEN
  THEN ;
: (STA-INPUT) ( -- ) STA-INPUT-A @ STA-INPUT-N @ STA-RX ;

PUBLIC
: WIFI-STATUS ( -- n ) STA-STATE @ ;
: WIFI-ERROR ( -- ior ) STA-ERROR @ ;
: WIFI-POLL ( -- )
  ['] (STA-POLL) CATCH STA-RESULT ;
: WIFI-INPUT ( a n -- ) STA-INPUT-N ! STA-INPUT-A ! ['] (STA-INPUT) CATCH STA-RESULT ;
: WIFI-TICK ( -- ) ['] STA-TIMEOUT CATCH STA-RESULT ;
: WIFI-JOIN ( i pmk -- )
  >R STA-SELECT R> STA-PMK 32 MOVE ['] STA-BEGIN CATCH STA-RESULT ;
: WIFI-DERIVE ( i pass n -- )
  >R >R STA-SELECT R> R> STA-SSID STA-SLEN @ STA-PMK WPA-PMK-START 1 STA-STATE! ;
: WIFI-WAIT ( -- ior )
  BEGIN WIFI-STATUS 1 6 WITHIN WHILE WIFI-POLL REPEAT WIFI-ERROR ;
: WIFI-TK ( -- a )
  STA-STATE @ 6 <> ABORT" WIFI: no installed key" STA-PTK 32 + ;
: WIFI-GROUP ( -- a id rsc )
  STA-STATE @ 6 <> ABORT" WIFI: no installed key" STA-GTK STA-GID @ STA-GRSC ;
: WIFI-RX-KEY ( id group? -- key rsc generation )
  STA-STATE @ 6 <> ABORT" WIFI: no installed key"
  IF
    DUP 0 4 WITHIN STA-NEED
    DUP 1 SWAP LSHIFT STA-GVALID @ AND 0<> STA-NEED
    DUP 16 * STA-GKEYS + OVER 6 * STA-GRSCS + ROT CELLS STA-GGEN + @
  ELSE
    0= STA-NEED STA-PTK 32 + STA-RXPN STA-PGEN @
  THEN ;
: WIFI-LEAVE ( -- )
  STA-KEYS-CLEAR STA-PMK 32 0 FILL WPA-PMK-CANCEL
  STA-SSID 32 0 FILL STA-RSN 128 0 FILL STA-OWN 6 0 FILL STA-PEER 6 0 FILL
  0 STA-SLEN ! 0 STA-RLEN ! 0 STA-AID ! 0 STA-ERROR ! 0 STA-STATE ! RADIO-BEACONS ;
END-PACKAGE
