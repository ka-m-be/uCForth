\ retry.fs - ESP32-RADIO: after an ACK timeout it sends again, with the same sequence, PN and bytes
\ ackhost.fs loads this file at its end.
ONLY FORTH DEFINITIONS ALSO MOCK-MAC ALSO ESP32-RADIO ALSO ESP32-RADIO.I
RADIO-START CONFIGURE
VARIABLE TRIES
: FAIL-ONCE ( -- )
  TX-CTRL @ TX-START-BITS AND IF
    1 TRIES +!
    4 0 TRIES @ 1 = IF $5000 ELSE 0 THEN EVENT IRQ
  THEN ;
0 TRIES ! 0 #ACK-STARTS ! ' FAIL-ONCE MAC-HOOK !
T{ SEND-ACK TRIES @ #ACK-STARTS @ TX-RETRIES @ -> 2 2 1 }T
T{ TX-TEST 1+ C@ 8 AND TX-BUF 1+ C@ 8 AND TX-TEST 22 + TX-BUF 22 + 2 SAME-BYTES? -> 0 8 TRUE }T

0 MAC-HOOK !
: ASYNC-ACK ( -- ) ACK-FRAME TRUE RADIO-TX-START ;
T{ ASYNC-ACK 4 0 $5000 EVENT IRQ RADIO-TX-POLL TX-RETRIES @ TX-ACTIVE? -> 1 1 TRUE }T
T{ 4 0 0 EVENT IRQ RADIO-TX-POLL TX-RETRIES @ TX-ACTIVE? -> 0 1 FALSE }T
0 #ACK-STARTS !
ASYNC-ACK
T{ 4 0 $5000 EVENT IRQ RADIO-TX-POLL -> 1 }T
T{ 4 0 $5000 EVENT IRQ RADIO-TX-POLL -> 1 }T
T{ 4 0 $5000 EVENT IRQ RADIO-TX-POLL -> 1 }T
T{ 4 0 $5000 EVENT IRQ RADIO-TX-POLL #ACK-STARTS @ TX-RETRIES @ TX-BLOCKED? -> -434 4 3 FALSE }T
T{ ASYNC-ACK 4 0 $3000 EVENT IRQ RADIO-TX-POLL TX-RETRIES @ -> -437 0 }T
T{ ASYNC-ACK 0 4 0 EVENT IRQ RADIO-TX-POLL TX-RETRIES @ -> -436 0 }T
TEST-MAC RADIO-STATION RADIO-SOFT-CCMP
: PROTECTED-ACK ( -- )
  48 SAMPLE 2DROP $08 TX-TEST C! $41 TX-TEST 1+ C!
  RADIO-MAC@ TX-TEST 10 + 6 MOVE TX-TEST 48 TRUE RADIO-TX-START ;
T{ PROTECTED-ACK 4 0 $5000 EVENT IRQ RADIO-TX-POLL -> 1 }T
T{ TX-TEST 24 + TX-BUF 24 + 8 SAME-BYTES? TX-TEST 1+ C@ TX-BUF 1+ C@ -> TRUE $41 $49 }T
T{ 4 0 0 EVENT IRQ RADIO-TX-POLL -> 0 }T
RADIO-STOP
S" retry" .RESULTS
