\ ccmpreg.fs - synthetic key slots and the metadata of hardware CCMP in ESP32-RADIO
ONLY FORTH DEFINITIONS ALSO FILES
[DEFINED] MOCK-MAC S" lib/esp32/test/radiohost.fs" ?INCLUDED
ONLY FORTH DEFINITIONS ALSO FILES
[DEFINED] OWN-FRAME S" lib/esp32/test/stahost.fs" ?INCLUDED
ONLY FORTH DEFINITIONS ALSO FILES
[DEFINED] ARRIVE-STA S" lib/esp32/test/starx.fs" ?INCLUDED
ONLY FORTH DEFINITIONS ALSO BYTES ALSO MOCK-MAC ALSO ESP32-RADIO ALSO ESP32-RADIO.I
16 BUFFER: SYNTH-KEY
SYNTH-KEY 16 $A5 FILL
START-STA
T{ SYNTH-KEY PEER 0 FALSE RADIO-CCMP-KEY! RADIO-CCMP? KEY-ENABLE @ -> TRUE 1 }T
T{ 0 KEY-SLOT @ 0 KEY-SLOT 4 + @ 0 KEY-SLOT 8 + @ 0 KEY-SLOT 24 + @ ->
   $53525102 $006C5554 $A5A5A5A5 0 }T
T{ SYNTH-KEY PEER 2 TRUE RADIO-CCMP-KEY! KEY-ENABLE @ 3 KEY-SLOT 4 + @ ->
   9 $80CC5554 }T
SYNTH-KEY 16 $5A FILL
T{ SYNTH-KEY PEER 2 TRUE RADIO-CCMP-KEY! KEY-ENABLE @ 3 KEY-SLOT 8 + @ 0 KEY-SLOT 8 + @ ->
   9 $5A5A5A5A $A5A5A5A5 }T
: BAD-ID ( -- ) SYNTH-KEY PEER 4 TRUE RADIO-CCMP-KEY! ;
T{ ' BAD-ID CATCH KEY-ENABLE @ -> -2 9 }T
T{ ' RADIO-SOFT-CCMP CATCH -> -2 }T
: HW-FRAME ( status interface-mask -- )
  0 43 FRAME 2DROP 55 SCRATCH 24 + !
  SCRATCH 3 + C! SCRATCH 27 + C! 8 $42 OWN-FRAME
  STA-FRAME SCRATCH RX-HEAD + 32 MOVE SCRATCH 72 ARRIVE ;
T{ 0 $10 HW-FRAME RECEIVED NIP RADIO-DECRYPTED? -> 43 TRUE }T
T{ 1 $10 HW-FRAME RECEIVED NIP RADIO-DECRYPTED? -> 44 FALSE }T
T{ 0 0 HW-FRAME RECEIVED NIP RADIO-DECRYPTED? -> 44 FALSE }T
: KEYS-EMPTY? ( -- f )
  TRUE 50 0 DO 0 KEY-SLOT I CELLS + @ 0= AND LOOP ;
T{ RADIO-KEYS-CLEAR RADIO-CCMP? KEY-ENABLE @ KEYS-EMPTY? -> FALSE 0 TRUE }T
: OTHERS-EMPTY? ( -- f ) TRUE 50 10 DO 0 KEY-SLOT I CELLS + @ 0= AND LOOP ;
T{ SYNTH-KEY PEER 0 FALSE RADIO-CCMP-KEY! OTHERS-EMPTY? -> TRUE }T   \ a key changes only its slot
RADIO-KEYS-CLEAR
T{ SYNTH-KEY PEER 0 FALSE RADIO-CCMP-KEY! RADIO-STOP KEY-ENABLE @ KEYS-EMPTY? -> 0 TRUE }T
S" ccmpreg" .RESULTS
