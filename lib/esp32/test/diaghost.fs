\ diaghost.fs - controlled ACK parameter changes, no hardware
ONLY FORTH DEFINITIONS  ALSO FILES
INCLUDE lib/esp32/test/radiohost.fs
INCLUDE lib/esp32/test/probe.fs
INCLUDE lib/esp32/test/ackdiag.fs
6 BUFFER: DIAG-MAC
$BBCCDDEE $02AA DIAG-MAC MAC-DECODE
VARIABLE TEST-CASE
: CHANGE ( -- )   TEST-CASE @ DIAG-CONFIG ;
: SEND-DIAG ( -- )   DIAG-MAC PROBE-BUILD DROP 24 FALSE RADIO-SEND ;
: RESULT ( -- result pmd active blocked )   TX-RESULT @ TX-LAST-PMD @ TX-ACTIVE? TX-BLOCKED? ;
T{ 0 ' DIAG-CONFIG CATCH NIP -> -2 }T
RADIO-START
: PREP ( -- )
  DIAG-MAC PROBE-BUILD DROP 24 FALSE 7 TX-PREPARE  $F3C0700A TX-CONFIG ! ;
T{ PREP 0 #WRITES ! 0 DIAG-CONFIG TX-CONFIG @ TX-PLCP1 @ #WRITES @ ->
   $F3C0700A $1000B01C 0 }T
T{ PREP 0 #WRITES ! 1 DIAG-CONFIG TX-CONFIG @ TX-PLCP1 @ #WRITES @ ->
   $F3C0700A $1000B01C 0 }T
T{ PREP 2 DIAG-CONFIG TX-CONFIG @ TX-PLCP1 @ -> $F3C0701E $1000B01C }T
T{ PREP 3 DIAG-CONFIG TX-CONFIG @ TX-PLCP1 @ -> $F3C0700A $0000B01C }T
T{ TX-CTRL @ TX-START-BITS AND -> 0 }T
-1 TEST-CASE !
T{ 0 #WRITES ! ' CHANGE CATCH #WRITES @ -> -2 0 }T
4 TEST-CASE !
T{ 0 #WRITES ! ' CHANGE CATCH #WRITES @ -> -2 0 }T
0 TEST-CASE !
TRUE TO TX-ACTIVE?
T{ 0 #WRITES ! ' CHANGE CATCH #WRITES @ -> -2 0 }T
FALSE TO TX-ACTIVE?  TRUE TO TX-BLOCKED?
T{ 0 #WRITES ! ' CHANGE CATCH #WRITES @ -> -2 0 }T
RADIO-STOP RADIO-START
0 MAC-HOOK !
T{ ' SEND-DIAG CATCH RESULT -> -2 TX-NO-END 0 FALSE TRUE }T
RADIO-STOP RADIO-START
T{ 0 #WRITES ! ' DRAIN-TEST-RX CATCH #WRITES @ -> -2 0 }T
RADIO-BEACONS
: FILL-BEACONS ( -- )   #RX 0 DO  $80 40 FRAME ARRIVE  LOOP ;
T{ FILL-BEACONS RX-NEXT @ RX-END = -> TRUE }T
T{ DRAIN-TEST-RX HELD RX-NEXT @ RX-END = -> 8 -1 FALSE }T
: END-FLAGS ( -- u )   0 #RX 0 DO  I DESC @ FRAME-END AND OR  LOOP ;
T{ END-FLAGS -> 0 }T
RADIO-STOP
T{ ' DRAIN-TEST-RX CATCH -> -2 }T
S" diaghost" .RESULTS
