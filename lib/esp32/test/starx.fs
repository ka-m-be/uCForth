\ starx.fs - ESP32-RADIO in station mode: which frames go to the program; the DMA and the handler
ONLY FORTH DEFINITIONS ALSO FILES
[DEFINED] MOCK-MAC S" lib/esp32/test/radiohost.fs" ?INCLUDED
ONLY FORTH DEFINITIONS ALSO FILES
[DEFINED] OWN-FRAME S" lib/esp32/test/stahost.fs" ?INCLUDED
ONLY FORTH DEFINITIONS ALSO BYTES ALSO MOCK-MAC ALSO ESP32-RADIO ALSO ESP32-RADIO.I
: START-STA ( -- ) RADIO-START STA-OWN RADIO-MAC! PEER RADIO-STATION ;
: ARRIVE-STA ( -- )
  0 32 FRAME 2DROP STA-FRAME SCRATCH RX-HEAD + 32 MOVE SCRATCH 60 ARRIVE ;

\ a beacon, a data frame, a protected one and a protected one to all: each goes to the program
START-STA
$80 0 OWN-FRAME ARRIVE-STA
8 2 OWN-FRAME ARRIVE-STA
8 $42 OWN-FRAME ARRIVE-STA
STA-FRAME 4 + 6 $FF FILL ARRIVE-STA
T{ MAC $2CC + @ #INTS @ -> 4 0 }T                 \ the DMA counts frames, not the handler
T{ MAC-INT #INTS @ -> 1 }T
T{ RECEIVED NIP RECEIVED NIP RECEIVED NIP RECEIVED NIP RECEIVED -> 32 32 32 32 0 0 }T
T{ #OTHER @ -> 0 }T
\ another sender, also to all, and a frame too short: given back unread
8 $42 OWN-FRAME STA-FRAME 10 + DUP C@ 2 XOR SWAP C! ARRIVE-STA
T{ RECEIVED #OTHER @ -> 0 0 1 }T
8 $42 OWN-FRAME STA-FRAME 4 + 6 $FF FILL
STA-FRAME 10 + DUP C@ 2 XOR SWAP C! ARRIVE-STA
T{ RECEIVED #OTHER @ -> 0 0 2 }T
T{ 0 8 FRAME ARRIVE RECEIVED #OTHER @ -> 0 0 3 }T
T{ 0 1700 FRAME ARRIVE RECEIVED #LONG @ MAC $2CC + @ -> 0 0 1 8 }T

\ software CCMP does not change the filters; a scan takes only beacons
RADIO-STOP START-STA
T{ RADIO-SOFT-CCMP FILTER @ FILTER-BITS AND -> 7 }T
$4000 FILTER BIS!
T{ RADIO-SOFT-CCMP FILTER @ $4000 AND FILTER @ FILTER-BITS AND -> $4000 7 }T
RADIO-BEACONS
T{ 8 $42 OWN-FRAME ARRIVE-STA RECEIVED #OTHER @ -> 0 0 1 }T
