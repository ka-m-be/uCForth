\ Reconfiguration cannot race a sender, even if its IRQ just finished.
VARIABLE CONFIG-ERROR
: CHANGE-MAC ( -- )
  TX-ACTIVE? IF
    0 MAC-HOOK !  ['] CONFIGURE CATCH CONFIG-ERROR !
    4 0 0 EVENT IRQ
  THEN ;
' CHANGE-MAC MAC-HOOK !
T{ SEND-ACK CONFIG-ERROR @ RA-LOW @ -> -2 $43424102 }T

