ONLY FORTH DEFINITIONS ALSO FILES
INCLUDE lib/net/test/wpasta.fs
ONLY FORTH DEFINITIONS ALSO FILES
PACKAGE CHIP
PUBLIC $400000 CONSTANT FLASH-SIZE
END-PACKAGE
PACKAGE FLASH
8192 BUFFER: STORAGE
STORAGE 8192 $FF FILL
: AT ( faddr -- a ) $3FE000 - STORAGE + ;
PUBLIC
VARIABLE WRITES VARIABLE FAIL-WRITE VARIABLE OMIT-COMMIT
: FLASH-READ ( faddr a n -- ior ) >R SWAP AT SWAP R> MOVE 0 ;
: FLASH-ERASE ( faddr n -- ior ) SWAP AT SWAP $FF FILL 0 ;
: FLASH-WRITE ( a n faddr -- ior )
  1 WRITES +! WRITES @ FAIL-WRITE @ = IF DROP 2DROP -37 EXIT THEN
  WRITES @ 2 = OMIT-COMMIT @ AND IF DROP 2DROP 0 EXIT THEN
  AT SWAP MOVE 0 ;
END-PACKAGE
S" lib/esp32/esp32/wlsave.fs" INCLUDED
ONLY FORTH DEFINITIONS ALSO BYTES ALSO WLAN ALSO WLAN.I ALSO WLSAVE ALSO WLSAVE.I ALSO FLASH ALSO FLASH.I
: SAVE ( -- ) 0 WRITES ! WLAN-SAVE ;
: LOAD ( -- ) WIFI-LEAVE 0 WLAN-JOIN ;
: EMPTY-PRIVATE? ( -- f )
  TRUE 128 0 DO
    REC-A I + C@ REC-B I + C@ OR WORK I + C@ OR 0= AND
  LOOP ;
T{ WLAN-SAVED? -> FALSE }T
FULL
T{ SAVE WLAN-SAVED? EMPTY-PRIVATE? -> TRUE TRUE }T
1 FAIL-WRITE ! $42 STA-PMK C!
T{ ' SAVE CATCH EMPTY-PRIVATE? -> -37 TRUE }T
T{ LOAD STA-PMK C@ -> 0 }T
FULL 2 FAIL-WRITE ! $42 STA-PMK C!
T{ ' SAVE CATCH EMPTY-PRIVATE? -> -37 TRUE }T
T{ LOAD STA-PMK C@ -> 0 }T
FULL 0 FAIL-WRITE ! $42 STA-PMK C!
T{ SAVE WLAN-SAVED? EMPTY-PRIVATE? -> TRUE TRUE }T
T{ LOAD STA-PMK C@ -> $42 }T
$3FF050 AT DUP C@ 1 XOR SWAP C!
T{ LOAD STA-PMK C@ EMPTY-PRIVATE? -> 0 TRUE }T
$3FE050 AT DUP C@ 1 XOR SWAP C!
T{ ' WLAN-SAVED? CATCH EMPTY-PRIVATE? -> -430 TRUE }T
T{ WLAN-FORGET WLAN-SAVED? EMPTY-PRIVATE? -> FALSE TRUE }T
FULL TRUE OMIT-COMMIT !
T{ ' SAVE CATCH EMPTY-PRIVATE? -> -432 TRUE }T
FALSE OMIT-COMMIT !
T{ WLAN-FORGET WLAN-SAVED? -> FALSE }T
S" wlsave" .RESULTS
