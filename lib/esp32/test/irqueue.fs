ONLY FORTH DEFINITIONS ALSO FILES
[DEFINED] T{ S" forth/test/tester.fs" ?INCLUDED
PACKAGE IR-MOCK
PUBLIC
1024 BUFFER: RAW
VARIABLE NOW VARIABLE READY VARIABLE END-US VARIABLE WORDS VARIABLE RELEASED
VARIABLE POS VARIABLE IDLE-INPUT VARIABLE ECHO-MODE VARIABLE SENDS
VARIABLE ENABLED
VARIABLE SEND-ERROR
VARIABLE START-ERROR
VARIABLE CAP-ERROR
: MICROS ( -- n ) NOW @ ;
: IR-CAP-POS ( -- n ) POS @ ;
: IR-CAP-LAST ( -- n ) END-US @ ;
: IR-CAP-PENDING? ( -- f ) READY @ ;
: IR-CAP-ON ( -- ) START-ERROR @ ?DUP IF THROW THEN TRUE ENABLED ! ;
: IR-CAP-OFF ( -- ) FALSE ENABLED ! ;
: IR-CAP-FRAME? ( -- a n end true | false )
  CAP-ERROR @ ?DUP IF THROW THEN
  READY @ IF RAW WORDS @ END-US @ TRUE ELSE FALSE THEN ;
: IR-CAP-RELEASE ( -- ) FALSE READY ! 1 RELEASED +! ;
: .IR-CAP ( -- ) ;
: RECEIVE3 ( -- )
  $00C88064 RAW ! $0000812C RAW CELL+ ! 2 WORDS !
  NOW @ END-US ! TRUE READY ! ;
: PIN@ ( pin -- f ) DROP IDLE-INPUT @ ;
: RMT-ON ; : RMT-HZ 80000000 ;
: RMT-DIV 2DROP ; : RMT-BLOCKS 2DROP ; : RMT-IDLE 2DROP ;
: RMT-CARRIER DROP 2DROP ; : RMT-OUT 2DROP ;
: INPUT DROP ; : RMT-IN-INV 2DROP ; : RMT-FILTER 2DROP ;
: RMT-END 2DROP ; : RMT-DEMOD 2DROP ;
: RMT-RX-ON DROP ; : RMT-RX-OFF DROP ;
: RMT-SEND ( a n ch -- )
  DROP 2DROP SEND-ERROR @ ?DUP IF THROW THEN 1 SENDS +!
  ECHO-MODE @ IF RECEIVE3
    ECHO-MODE @ 2 = IF $00008190 RAW CELL+ ! THEN
  THEN ;
: RMT-RAM ( ch -- a ) DROP RAW ;
: RMT-RECEIVED ( ch -- n ) DROP 0 ;
: RMT-RX-INT 2DROP ;
VARIABLE INT-XT
: INT! DROP INT-XT ! ; : INT-ON DROP ; : INT-OFF DROP ; : +INT ;
47 CONSTANT RMT-SOURCE
: EVERY 2DROP ; : IDLE+ DROP ; : IDLE- DROP ;
END-PACKAGE
: RMT IR-MOCK ; : GPIO IR-MOCK ; : INTR IR-MOCK ;
: IR-CAPTURE IR-MOCK ; : TIMERS IR-MOCK ; : IDLE IR-MOCK ; : CHIP IR-MOCK ;
ONLY FORTH DEFINITIONS ALSO FILES
INCLUDE lib/esp32/ir.fs
ONLY FORTH DEFINITIONS ALSO FILES
INCLUDE lib/esp32/irqueue.fs
ONLY FORTH DEFINITIONS ALSO IR-MOCK ALSO IR ALSO IR-QUEUE ALSO IR-QUEUE.I
CREATE THREE 100 , 200 , 300 ,
: FIRST-FRAME ( -- first f )
  IR-Q-FRAME? IF 2DROP @ TRUE ELSE 0 FALSE THEN ;
TRUE IDLE-INPUT !
4 14 IR-Q-START
T{ RECEIVE3 IR-Q-TICK RECEIVED @ RELEASED @ -> 1 1 }T
T{ FIRST-FRAME -> 100 TRUE }T
T{ IR-Q-FRAME? -> FALSE }T
: FILL-QUEUE ( -- ) 17 0 DO RECEIVE3 IR-Q-TICK LOOP ;
T{ FILL-QUEUE FULL-N @ WRITE-N @ READ-N @ - -> 1 16 }T
IR-Q-STOP 4 14 IR-Q-START
T{ THREE 3 IR-Q-SEND IR-Q-RESULT -> 0 1 }T
T{ THREE 3 IR-Q-SEND -> -451 }T
14999 NOW !
T{ IR-Q-CONTROL SENDS @ -> 0 }T
1 NOW +! 1 ECHO-MODE !
T{ IR-Q-CONTROL SENDS @ MIN-QUIET @ -> 1 15000 }T
T{ IR-Q-TICK IR-Q-RESULT RECEIVED @ -> 0 0 }T
T{ THREE 3 IR-Q-SEND -> 0 }T
14999 NOW +! 1 POS +!
T{ IR-Q-CONTROL SENDS @ -> 1 }T
15000 NOW +!
T{ IR-Q-CONTROL IR-Q-TICK IR-Q-RESULT SENDS @ -> 0 2 }T
IR-Q-STOP 4 14 IR-Q-START
0 ECHO-MODE !
T{ THREE 3 IR-Q-SEND -> 0 }T
FALSE IDLE-INPUT ! 2000001 NOW +!
T{ IR-Q-CONTROL IR-Q-RESULT -> -452 }T
TRUE IDLE-INPUT ! IR-Q-STOP 4 14 IR-Q-START
2 ECHO-MODE !
: WRONG-ECHO ( -- )
  15000 NOW +! IR-Q-CONTROL IR-Q-TICK IR-Q-CONTROL ;
T{ THREE 3 IR-Q-SEND WRONG-ECHO WRONG-ECHO WRONG-ECHO IR-Q-RESULT ATTEMPTS @ -> 0 -453 3 }T
T{ THREE 0 IR-Q-SEND -> -450 }T
T{ THREE 401 IR-Q-SEND -> -450 }T
CREATE BAD-TIME 0 ,
T{ BAD-TIME 1 IR-Q-SEND -> -450 }T
IR-Q-STOP 4 14 IR-Q-START
: RAW-TIMES ( n -- )
  DUP 2/ WORDS ! 0 ?DO $00C88064 RAW I 2/ CELLS + ! 2 +LOOP
  0 RAW WORDS @ CELLS + ! 1 WORDS +! NOW @ END-US ! TRUE READY ! ;
: DECODE-ALL ( -- ) 20 0 DO IR-Q-TICK LOOP ;
T{ 400 RAW-TIMES DECODE-ALL FIRST-FRAME -> 100 TRUE }T
IR-Q-FRAME? DROP
T{ 402 RAW-TIMES DECODE-ALL IR-Q-FRAME? LONG-N @ -> FALSE 1 }T
IR-Q-STOP 4 14 IR-Q-START
-2 SEND-ERROR ! FALSE IR-ECHO !
T{ THREE 3 IR-Q-SEND -> 0 }T
15000 NOW +!
T{ IR-Q-CONTROL IR-Q-RESULT IR-ECHO @ BUSY @ -> -2 FALSE FALSE }T
0 SEND-ERROR !
IR-Q-STOP
T{ THREE 3 IR-Q-SEND ENABLED @ -> -454 FALSE }T
-2 START-ERROR !
: FAILED-START ( -- ) 4 14 IR-Q-START ;
T{ ' FAILED-START CATCH RUNNING @ ENABLED @ -> -2 FALSE FALSE }T
0 START-ERROR !
T{ 4 14 IR-Q-START RUNNING @ ENABLED @ -> TRUE TRUE }T
IR-Q-STOP
\ A frame in the echo window that is not the echo goes into the ring (10 times, 3 were sent).
4 14 IR-Q-START 0 ECHO-MODE !
0 SENDS !
T{ THREE 3 IR-Q-SEND 15000 NOW +! IR-Q-CONTROL SENDS @ -> 0 1 }T
T{ 10 RAW-TIMES DECODE-ALL RECEIVED @ ECHO-BAD @ IR-Q-RESULT -> 1 1 1 }T
T{ FIRST-FRAME -> 100 TRUE }T
IR-Q-STOP
\ A long echo: the timer compares it in parts of 32 times.
4 14 IR-Q-START
400 CELLS BUFFER: LONG-FRAME
: FILL-LONG ( -- ) 400 0 DO I 1 AND IF 200 ELSE 100 THEN LONG-FRAME I CELLS + ! LOOP ;
FILL-LONG
T{ LONG-FRAME 399 IR-Q-SEND 15000 NOW +! IR-Q-CONTROL -> 0 }T
400 RAW-TIMES $00008064 RAW 199 CELLS + !   \ the last word: light, then the end (399 times)
: TICKS ( n -- ) 0 ?DO IR-Q-TICK LOOP ;
T{ 13 TICKS IR-Q-RESULT COMPARE-I @ 0< 0= -> 1 TRUE }T
T{ 20 TICKS IR-Q-RESULT RECEIVED @ -> 0 0 }T
IR-Q-STOP
\ An error in a step is counted; the service goes on.
4 14 IR-Q-START
T{ -9 CAP-ERROR ! IR-Q-TICK ERROR @ RUNNING @ -> -9 TRUE }T
T{ 0 CAP-ERROR ! RECEIVE3 IR-Q-TICK RECEIVED @ -> 1 }T
IR-Q-STOP
