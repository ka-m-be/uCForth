CREATE THREE 100 , 200 , 300 ,
: FIRST-FRAME ( -- first f )
  IR-Q-FRAME? IF 2DROP @ TRUE ELSE 0 FALSE THEN ;
16 IR-Q-SLOT * BUFFER: TEST-RING
: Q-START ( -- )   TEST-RING 16 IR-Q-SLOT * 4 14 IR-Q-START ;   \ a ring of 16 frames
IDLE-INPUT ON!
Q-START
T{ RECEIVE3 IR-Q-TICK RECEIVED @ RELEASED @ -> 1 1 }T
T{ FIRST-FRAME -> 100 TRUE }T
T{ IR-Q-FRAME? -> FALSE }T
: FILL-QUEUE ( -- ) 17 0 DO RECEIVE3 IR-Q-TICK LOOP ;
T{ FILL-QUEUE FULL-N @ WRITE-N @ READ-N @ - -> 1 16 }T
IR-Q-STOP Q-START
T{ THREE 3 IR-Q-SEND IR-Q-RESULT -> 0 1 }T
T{ THREE 3 IR-Q-SEND -> -451 }T
14999 NOW !
T{ IR-Q-CONTROL SENDS @ -> 0 }T
1 NOW +! 1 ECHO-MODE !
T{ IR-Q-CONTROL SENDS @ MIN-QUIET @ -> 1 15000 }T
T{ IR-Q-TICK IR-Q-RESULT RECEIVED @ -> 0 0 }T
T{ THREE 3 IR-Q-SEND -> 0 }T
14999 NOW +! 1 POS +!
T{ IR-Q-CONTROL SENDS @ -> 1 }T
15000 NOW +!
T{ IR-Q-CONTROL IR-Q-TICK IR-Q-RESULT SENDS @ -> 0 2 }T
IR-Q-STOP Q-START
0 ECHO-MODE !
T{ THREE 3 IR-Q-SEND -> 0 }T
IDLE-INPUT OFF! 2000001 NOW +!
T{ IR-Q-CONTROL IR-Q-RESULT -> -452 }T
IDLE-INPUT ON! IR-Q-STOP Q-START
\ The echo has as many times as were sent; their lengths do not count.
: ONE-SEND ( -- )   15000 NOW +! IR-Q-CONTROL IR-Q-TICK IR-Q-CONTROL ;
2 ECHO-MODE !  0 SENDS !
T{ THREE 3 IR-Q-SEND ONE-SEND IR-Q-RESULT ECHO-BAD @ RECEIVED @ -> 0 0 0 0 }T
\ Another number of times: -453 at once, no second attempt; that frame goes into the ring.
3 ECHO-MODE !
T{ THREE 3 IR-Q-SEND ONE-SEND IR-Q-RESULT ECHO-BAD @ RECEIVED @ -> 0 -453 1 1 }T
T{ ONE-SEND SENDS @ -> 2 }T
\ No echo within 100 ms: -453.
0 ECHO-MODE !
T{ THREE 3 IR-Q-SEND ONE-SEND IR-Q-RESULT -> 0 1 }T
100000 NOW +!
T{ IR-Q-CONTROL IR-Q-RESULT ECHO-BAD @ SENDS @ -> -453 2 3 }T
T{ THREE 0 IR-Q-SEND -> -450 }T
T{ THREE 401 IR-Q-SEND -> -450 }T
CREATE BAD-TIME 0 ,
T{ BAD-TIME 1 IR-Q-SEND -> -450 }T
IR-Q-STOP Q-START
: RAW-TIMES ( n -- )
  DUP 2/ WORDS ! 0 ?DO $00C88064 RAW I 2/ CELLS + ! 2 +LOOP
  0 RAW WORDS @ CELLS + ! 1 WORDS +! NOW @ END-US ! READY ON! ;
: DECODE-ALL ( -- ) 20 0 DO IR-Q-TICK LOOP ;
T{ 400 RAW-TIMES DECODE-ALL FIRST-FRAME -> 100 TRUE }T
IR-Q-FRAME? DROP
T{ 402 RAW-TIMES DECODE-ALL IR-Q-FRAME? LONG-N @ -> FALSE 1 }T
IR-Q-STOP Q-START
-2 SEND-ERROR ! IR-ECHO OFF!
T{ THREE 3 IR-Q-SEND -> 0 }T
15000 NOW +!
T{ IR-Q-CONTROL IR-Q-RESULT IR-ECHO @ BUSY @ -> -2 FALSE FALSE }T
0 SEND-ERROR !
IR-Q-STOP
T{ THREE 3 IR-Q-SEND ENABLED @ -> -454 FALSE }T
-2 START-ERROR !
: FAILED-START ( -- ) Q-START ;
T{ ' FAILED-START CATCH RUNNING @ ENABLED @ -> -2 FALSE FALSE }T
0 START-ERROR !
T{ Q-START RUNNING @ ENABLED @ -> TRUE TRUE }T
IR-Q-STOP
\ A frame in the place of the echo with 10 times (3 were sent) goes into the ring; the send ends with -453.
Q-START 0 ECHO-MODE !
0 SENDS !
T{ THREE 3 IR-Q-SEND 15000 NOW +! IR-Q-CONTROL SENDS @ -> 0 1 }T
T{ 10 RAW-TIMES DECODE-ALL RECEIVED @ ECHO-BAD @ IR-Q-RESULT -> 1 1 -453 }T
T{ FIRST-FRAME -> 100 TRUE }T
IR-Q-STOP
\ A long echo (399 times): the send is done in the step that decodes its end, the 13th.
Q-START
400 CELLS BUFFER: LONG-FRAME
: FILL-LONG ( -- ) 400 0 DO I 1 AND IF 200 ELSE 100 THEN LONG-FRAME I CELLS + ! LOOP ;
FILL-LONG
T{ LONG-FRAME 399 IR-Q-SEND 15000 NOW +! IR-Q-CONTROL -> 0 }T
400 RAW-TIMES $00008064 RAW 199 CELLS + !   \ the last word: light, then the end (399 times)
: TICKS ( n -- ) 0 ?DO IR-Q-TICK LOOP ;
T{ 12 TICKS IR-Q-RESULT -> 1 }T
T{ 1 TICKS IR-Q-RESULT RECEIVED @ -> 0 0 }T
IR-Q-STOP
\ An error in a step is counted; the service goes on.
Q-START
T{ -9 CAP-ERROR ! IR-Q-TICK ERROR @ RUNNING @ -> -9 TRUE }T
T{ 0 CAP-ERROR ! RECEIVE3 IR-Q-TICK RECEIVED @ -> 1 }T
IR-Q-STOP
\ The ring of the program: u / IR-Q-SLOT frames. A ring of 3: the fourth
\ frame finds no room; the frames come in order, also over the end of the ring.
3 IR-Q-SLOT * BUFFER: SMALL-RING
: SMALL-START ( -- )   SMALL-RING 3 IR-Q-SLOT * 4 14 IR-Q-START ;
: AT-US ( us -- )   NOW !  RECEIVE3 IR-Q-TICK ;        \ a frame that ends at us
: END-OF ( -- us | 0 )   IR-Q-FRAME? IF NIP NIP ELSE 0 THEN ;
SMALL-START
T{ #SLOTS @  10 AT-US 20 AT-US 30 AT-US 40 AT-US  RECEIVED @ FULL-N @ -> 3 3 1 }T
T{ END-OF END-OF END-OF -> 10 20 30 }T
T{ 50 AT-US 60 AT-US 70 AT-US  FULL-N @ -> 2 }T              \ 30 is held: room for two
T{ END-OF END-OF END-OF -> 50 60 0 }T
\ IR-Q-STOP clears the ring and gives it back
T{ 80 AT-US  SMALL-RING @  IR-Q-STOP  SMALL-RING @  RING @ -> 3 0 0 }T
\ no ring, or one too small for a frame
: NO-RING ( -- )   0 IR-Q-SLOT 4 14 IR-Q-START ;
: SHORT-RING ( -- )   SMALL-RING IR-Q-SLOT 1- 4 14 IR-Q-START ;
T{ ' NO-RING CATCH  RUNNING @ ENABLED @ -> -2 FALSE FALSE }T
T{ ' SHORT-RING CATCH  RUNNING @ -> -2 FALSE }T
