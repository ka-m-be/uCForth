\ irmock.fs - the hardware of IR and IR-QUEUE as mocks: raw frames, no pins, RF or ROM calls
\ The names of the packages RMT GPIO INTR IR-CAPTURE TIMERS IDLE CHIP give IR-MOCK, so
\ lib/esp32/ir.fs and lib/esp32/esp32/irqueue.fs load on the host (lib/esp32/test/irqueue.fs,
\ lib/test/heads.fs).
ONLY FORTH DEFINITIONS
PACKAGE IR-MOCK
PUBLIC
1024 BUFFER: RAW
VARIABLE NOW VARIABLE READY VARIABLE END-US VARIABLE WORDS VARIABLE RELEASED
VARIABLE POS VARIABLE IDLE-INPUT VARIABLE ECHO-MODE VARIABLE SENDS
VARIABLE ENABLED
VARIABLE SEND-ERROR
VARIABLE START-ERROR
VARIABLE CAP-ERROR
: MICROS ( -- n ) NOW @ ;
: IR-CAP-POS ( -- n ) POS @ ;
: IR-CAP-LAST ( -- n ) END-US @ ;
: IR-CAP-PENDING? ( -- f ) READY @ ;
: IR-CAP-ON ( -- ) START-ERROR @ ?DUP IF THROW THEN ENABLED ON! ;
: IR-CAP-OFF ( -- ) ENABLED OFF! ;
: IR-CAP-FRAME? ( -- a n end true | false )
  CAP-ERROR @ ?DUP IF THROW THEN
  READY @ IF RAW WORDS @ END-US @ TRUE ELSE FALSE THEN ;
: IR-CAP-RELEASE ( -- ) READY OFF! 1 RELEASED +! ;
: .IR-CAP ( -- ) ;
: RECEIVE3 ( -- )
  $00C88064 RAW ! $0000812C RAW CELL+ ! 2 WORDS !
  NOW @ END-US ! READY ON! ;
: PIN@ ( pin -- f ) DROP IDLE-INPUT @ ;
: RMT-ON ; : RMT-HZ 80000000 ;
: RMT-DIV 2DROP ; : RMT-BLOCKS 2DROP ; : RMT-IDLE 2DROP ;
: RMT-CARRIER DROP 2DROP ; : RMT-OUT 2DROP ;
: INPUT DROP ; : RMT-IN-INV 2DROP ; : RMT-FILTER 2DROP ;
: RMT-END 2DROP ; : RMT-DEMOD 2DROP ;
: RMT-RX-ON DROP ; : RMT-RX-OFF DROP ;
: RMT-SEND ( a n ch -- )   \ ECHO-MODE 1: the echo; 2: its last time 400, not 300; 3: without it
  DROP 2DROP SEND-ERROR @ ?DUP IF THROW THEN 1 SENDS +!
  ECHO-MODE @ IF RECEIVE3
    ECHO-MODE @ 2 = IF $00008190 RAW CELL+ ! THEN
    ECHO-MODE @ 3 = IF 0 RAW CELL+ ! THEN
  THEN ;
: RMT-RAM ( ch -- a ) DROP RAW ;
: RMT-RECEIVED ( ch -- n ) DROP 0 ;
: RMT-RX-INT 2DROP ;
VARIABLE INT-XT
: INT! DROP INT-XT ! ; : INT-ON DROP ; : INT-OFF DROP ; : +INT ;
47 CONSTANT RMT-SOURCE
: EVERY 2DROP ; : IDLE+ DROP ; : IDLE- DROP ;
END-PACKAGE
: RMT IR-MOCK ; : GPIO IR-MOCK ; : INTR IR-MOCK ;
: IR-CAPTURE IR-MOCK ; : TIMERS IR-MOCK ; : IDLE IR-MOCK ; : CHIP IR-MOCK ;
