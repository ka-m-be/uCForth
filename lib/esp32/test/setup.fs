PACKAGE NETIF
PUBLIC
VARIABLE LOCAL-IP
: NET-STATIC ( ip mask gateway dns -- ) DROP 2DROP LOCAL-IP ! ;
: NET-DOWN ( -- ) 0 LOCAL-IP ! ;
END-PACKAGE
PACKAGE NET-TIMER
PUBLIC
: NET-START ( -- ) ;
: NET-STOP ( -- ) ;
END-PACKAGE
PACKAGE DHCP-SERVER
PUBLIC
VARIABLE DHCP-ACTIVE
: DHCPS-START ( peer ip -- ) 2DROP TRUE DHCP-ACTIVE ! ;
: DHCPS-STOP ( -- ) FALSE DHCP-ACTIVE ! ;
: DHCPS-RUNNING? ( -- f ) DHCP-ACTIVE @ ;
: DHCPS-TICK ( -- ) ;
: .DHCPS ( -- ) ;
END-PACKAGE
PACKAGE WLAN-BACK
PUBLIC
: WBACK-RUNNING? ( -- f ) FALSE ;
END-PACKAGE
PACKAGE RADIO-LINK
PUBLIC
VARIABLE AP-MODE
: LINK-ACCESS ( -- ) TRUE AP-MODE ! ;
: LINK-STATION ( -- ) FALSE AP-MODE ! ;
END-PACKAGE
