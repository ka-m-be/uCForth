: START-SETUP ( -- ) S" ucf-setup" 6 SETUP-START ;
T{ START-SETUP ACTIVE @ RADIO-CHANNEL@ LOCAL-IP @ AP-MODE @ -> TRUE 6 $C0A84D01 TRUE }T
T{ SERVICE DHCPS-RUNNING? -> FALSE }T
T{ ' START-SETUP CATCH ACTIVE @ RADIO-CHANNEL@ -> -2 TRUE 6 }T
OWN-CLIENT PEER 6 MOVE 2 AP-STATE !
T{ SERVICE DHCPS-RUNNING? -> TRUE }T
T{ SETUP-STOP ACTIVE @ RADIO-CHANNEL@ DHCPS-RUNNING? LOCAL-IP @ AP-MODE @ -> FALSE 0 FALSE 0 FALSE }T
T{ SETUP-STOP ACTIVE @ -> FALSE }T
S" setup" .RESULTS
