\ airping.fs - package AIR-IP: an ICMP echo to the gateway over the WLAN of the board (a test)
\ AIR-PING ( -- ms | -1 ) after DHCP; load it in ucf term over the image of apps/irbridge.
\ NETIF is locked while the probe reads LINK, so NET-STEP cannot take
\ its reply. Only counts and times are shown; no packet bytes.
PACKAGE AIR-IP ALSO NET ALSO NETIF ALSO LINK ALSO LINK-NET.I ALSO INET ALSO IPV4 ALSO ARP ALSO TCP ALSO DHCP
LINK-MTU 14 + BUFFER: AIP-FRAME
VARIABLE AIP-A
VARIABLE AIP-ANSWER
VARIABLE AIP-SEQUENCE
?: LINK-TICK ( -- ) ;
: ECHO? ( a n -- f )
  66 < IF DROP FALSE EXIT THEN AIP-A !
  AIP-A @ 12 + BE16@ $0800 =
  AIP-A @ 14 + C@ $45 = AND AIP-A @ 16 + BE16@ 52 = AND
  AIP-A @ 23 + C@ 1 = AND
  AIP-A @ 26 + BE32@ GATEWAY = AND AIP-A @ 30 + BE32@ MY-IP = AND
  AIP-A @ 34 + BE16@ 0= AND
  AIP-A @ 38 + BE16@ $CFA1 = AND
  AIP-A @ 40 + BE16@ AIP-SEQUENCE @ $FFFF AND = AND
  0 AIP-A @ 14 + 20 IP-SUM IP-FOLD 0= AND
  0 AIP-A @ 34 + 32 IP-SUM IP-FOLD 0= AND ;
: SERVE ( -- )
  NET-CONTROL LINK-TICK
  BEGIN AIP-FRAME LINK-RECEIVE ?DUP WHILE
    AIP-FRAME SWAP 2DUP ECHO? IF MILLIS AIP-ANSWER ! THEN FRAME-IN
  REPEAT
  IP-FLUSH ARP-TICK TCP-TICK DHCP-TICK ;
: PROBE ( -- ms | -1 )
  MY-IP 0= GATEWAY 0= OR ABORT" AIR-IP: DHCP first"
  1 AIP-SEQUENCE +! 0 AIP-ANSWER !
  IP-DATA 32 0 FILL 8 IP-DATA C!
  $CFA1 IP-DATA 4 + BE16! AIP-SEQUENCE @ IP-DATA 6 + BE16!
  0 IP-DATA 32 IP-SUM IP-FOLD IP-DATA 2 + BE16!
  1 32 GATEWAY IP-SEND THROW MILLIS
  BEGIN
    SERVE AIP-ANSWER @ IF AIP-ANSWER @ SWAP - EXIT THEN
    MILLIS OVER - 2000 < 0=
  UNTIL DROP -1 ;
PUBLIC
: AIR-PING ( -- ms | -1 ) ['] PROBE LOCKED ;
END-PACKAGE
