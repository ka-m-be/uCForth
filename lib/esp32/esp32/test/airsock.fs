\ airsock.fs - package AIR-SOCK: UDP and TCP over the WLAN of the board, against a host (a test)
\ The host runs lib/net/test/echopeer.fs: it echoes UDP on 37021 and TCP on 47021.
\ For the server tests the host connects to the board on UDP 37022 and TCP 47022.
\ Example, after WBACK-READY?:  192 168 1 20 IP AIR-UDP-CLIENT  S" 192.168.1.20" AIR-TCP-CLIENT
PACKAGE AIR-SOCK ALSO NET ALSO INET
1000 BUFFER: OUT
1000 BUFFER: IN
VARIABLE CLIENT
VARIABLE USOCK
VARIABLE SERVER
VARIABLE PEER
VARIABLE REMOTE
VARIABLE TOTAL
VARIABLE GOT
: PATTERN ( -- ) 1000 0 DO I 255 AND OUT I + C! LOOP ;
: SAME? ( n -- f ) TRUE SWAP 0 ?DO IN I + C@ OUT I + C@ = AND LOOP ;
: READ-ALL ( sock -- )
  CLIENT ! 0 GOT !
  BEGIN GOT @ 1000 < WHILE
    IN GOT @ + 1000 GOT @ - CLIENT @ SOCK-READ THROW
    DUP 0= ABORT" AIR-SOCK: no bytes" GOT +!
  REPEAT ;
: UDP-ANSWER ( -- f )
  IN 1000 USOCK @ UDP-RECEIVE IF
    37021 = SWAP REMOTE @ = AND
    OVER 1000 = AND SWAP 1000 = IF 1000 SAME? AND THEN
  ELSE FALSE THEN ;
PUBLIC
: AIR-UDP-CLIENT ( ip -- )
  REMOTE ! PATTERN 0 UDP-OPEN THROW USOCK !
  OUT 1000 REMOTE @ 37021 USOCK @ UDP-SEND THROW
  MILLIS BEGIN
    UDP-ANSWER IF DROP USOCK @ SOCK-CLOSE THROW ." UDP echo 1000: ok" CR EXIT THEN
    NET-POLL MILLIS OVER - 2000 >
  UNTIL DROP USOCK @ SOCK-CLOSE THROW TRUE ABORT" AIR-SOCK: UDP echo timeout" ;
: AIR-TCP-CLIENT ( a n -- )
  47021 TCP-OPEN THROW CLIENT ! PATTERN 0 TOTAL ! MILLIS
  10 0 DO
    OUT 1000 CLIENT @ SOCK-WRITE THROW CLIENT @ READ-ALL
    1000 SAME? 0= ABORT" AIR-SOCK: TCP echo differs"
    2000 TOTAL +!
  LOOP
  MILLIS SWAP - ." TCP echo bytes/ms: " TOTAL @ . . CR
  CLIENT @ SOCK-CLOSE THROW ;
: AIR-UDP-SERVER ( -- )
  37022 UDP-OPEN THROW USOCK ! MILLIS
  BEGIN
    IN 1000 USOCK @ UDP-RECEIVE IF
      >R >R IN SWAP R> R> USOCK @ UDP-SEND THROW
      DROP USOCK @ SOCK-CLOSE THROW ." UDP server: ok" CR EXIT
    THEN
    NET-POLL MILLIS OVER - 5000 >
  UNTIL DROP USOCK @ SOCK-CLOSE THROW TRUE ABORT" AIR-SOCK: UDP client timeout" ;
: AIR-TCP-SERVER ( -- )
  47022 TCP-LISTEN THROW SERVER ! MILLIS
  BEGIN
    SERVER @ TCP-ACCEPT IF PEER ! DROP
      PEER @ READ-ALL IN 1000 PEER @ SOCK-WRITE THROW
      MILLIS 500 + BEGIN NET-POLL DUP MILLIS - 0< UNTIL DROP
      PEER @ SOCK-CLOSE THROW SERVER @ SOCK-CLOSE THROW
      ." TCP server 1000: ok" CR EXIT
    THEN
    NET-POLL MILLIS OVER - 5000 >
  UNTIL DROP SERVER @ SOCK-CLOSE THROW TRUE ABORT" AIR-SOCK: TCP client timeout" ;
END-PACKAGE
