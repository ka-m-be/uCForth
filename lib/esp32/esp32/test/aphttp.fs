\ aphttp.fs - package AP-HTTP: a fixed HTTP reply for the browser of the setup device (a test)
\ AP-HTTP-START serves "ucf setup AP: ok" on port 8080; AP-HTTP-STOP ends it.
\ This is a test endpoint, not the planned application web server.
PACKAGE AP-HTTP ALSO NET ALSO IDLE
VARIABLE SERVER VARIABLE PEER VARIABLE ANSWER-N VARIABLE REQUESTS
128 BUFFER: REQUEST
CREATE ANSWER
S" HTTP/1.0 200 OK" HERE OVER ALLOT SWAP MOVE $0D C, $0A C,
S" Content-Type: text/plain" HERE OVER ALLOT SWAP MOVE $0D C, $0A C,
S" Content-Length: 16" HERE OVER ALLOT SWAP MOVE $0D C, $0A C,
S" Connection: close" HERE OVER ALLOT SWAP MOVE $0D C, $0A C,
$0D C, $0A C,
S" ucf setup AP: ok" HERE OVER ALLOT SWAP MOVE $0A C,
HERE ANSWER - ANSWER-N !
: SERVE ( -- )
  PEER @ 0= IF SERVER @ TCP-ACCEPT IF PEER ! THEN EXIT THEN
  PEER @ SOCK-AVAILABLE 0= IF EXIT THEN
  BEGIN PEER @ SOCK-AVAILABLE WHILE REQUEST 128 PEER @ SOCK-READ THROW DROP REPEAT
  ANSWER ANSWER-N @ PEER @ SOCK-WRITE THROW
  PEER @ SOCK-CLOSE THROW 0 PEER ! 1 REQUESTS +! ;
PUBLIC
: AP-HTTP-START ( -- )
  SERVER @ ABORT" AP-HTTP: already running"
  8080 TCP-LISTEN THROW SERVER ! 0 PEER ! 0 REQUESTS ! ['] SERVE IDLE+ ;
: AP-HTTP-STOP ( -- )
  ['] SERVE IDLE-
  PEER @ ?DUP IF SOCK-CLOSE THROW THEN
  SERVER @ ?DUP IF SOCK-CLOSE THROW THEN 0 SERVER ! 0 PEER ! ;
: .AP-HTTP ( -- ) ." browser requests: " REQUESTS @ . CR ;
END-PACKAGE
