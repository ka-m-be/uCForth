\ irqbusy.fs - synthetic IR frames on GPIO 25 again and again, while the console and the WLAN work
\ Load irqueue.fs (this folder) first; no light. A frame every 20.6 ms, three times per frame.
ONLY FORTH DEFINITIONS ALSO RMT ALSO RMT.I ALSO IR.I ALSO IR-QUEUE ALSO IR-QUEUE.I
ALSO IR-CAPTURE ALSO IR-CAPTURE.I ALSO GPIO
: LOOP-ON ( -- )
  100 1 200 0 PULSE TX RMT-RAM !
  300 1 20000 0 PULSE TX RMT-RAM CELL+ !
  0 TX RMT-RAM 2 CELLS + !
  $20 TX CONF1 BIC! 8 TX CONF1 BIS! 8 TX CONF1 BIC!
  $40 TX CONF1 BIS! 1 TX CONF1 BIS! ;
: LOOP-OFF ( -- )
  BEGIN 25 PIN@ 0= UNTIL
  $41 TX CONF1 BIC! 0 TX RMT-RAM !
  8 TX CONF1 BIS! 8 TX CONF1 BIC! 30 MS ;
: COMPUTE ( ms -- ) MILLIS + BEGIN DUP MILLIS - 0< UNTIL DROP ;
: THREE? ( a n -- f )
  3 <> IF DROP FALSE EXIT THEN
  DUP @ 100 - ABS 40 < OVER CELL+ @ 200 - ABS 40 < AND
  SWAP 2 CELLS + @ 300 - ABS 40 < AND ;
VARIABLE VERIFIED VARIABLE WRONG
: CHECK-FRAMES ( -- )
  0 VERIFIED ! 0 WRONG !
  BEGIN IR-Q-FRAME? WHILE
    DROP THREE? IF 1 VERIFIED +! ELSE 1 WRONG +! THEN
  REPEAT ;

IR-Q-STOP LOOPBACK
LOOP-ON 200 COMPUTE LOOP-OFF
CHECK-FRAMES
T{ VERIFIED @ 8 12 WITHIN WRONG @ FULL-N @ LONG-N @ -> TRUE 0 0 0 }T
LOOP-ON 500 COMPUTE LOOP-OFF
CHECK-FRAMES
T{ VERIFIED @ FULL-N @ 0 > WRONG @ C-FULL CAP@ -> 16 TRUE 0 0 }T
T{ STEP-MAX @ 1000 < -> TRUE }T
.IR-Q
IR-Q-STOP 25 INPUT
S" irqbusy (board)" .RESULTS
