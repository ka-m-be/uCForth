\ wlsave.fs - WROOM 4 MB: two reserved profile sectors, SSID and PMK only
\ No plaintext password. Commit last; keep the previous valid sector.
PACKAGE WLSAVE ALSO WLAN ALSO WLAN.I ALSO WIFI ALSO FLASH ALSO CHIP ALSO SHA1 ALSO BYTES
: CHECK-MAP ( -- ) FLASH-SIZE $400000 <> ABORT" WLSAVE needs the 4-MB WROOM flash map" ;
CHECK-MAP
$3FE000 CONSTANT SLOT-A
$3FF000 CONSTANT SLOT-B
$314E4C57 CONSTANT MAGIC
$54494D43 CONSTANT COMMIT
128 BUFFER: REC-A
128 BUFFER: REC-B
128 BUFFER: WORK
VARIABLE VALID-A VARIABLE VALID-B VARIABLE ACTIVE
VARIABLE DESTINATION VARIABLE NEXT-SEQ
: WIPE ( -- )
  REC-A 128 0 FILL REC-B 128 0 FILL WORK 128 0 FILL SHA1-CLEAR ;
: VALID ( a -- status )
  DUP @ MAGIC <> IF
    DUP @ -1 <> IF ." WLAN: unrecognized profile slot, not loaded" CR THEN DROP 0 EXIT
  THEN
  DUP 96 + @ COMMIT <> IF DROP ." WLAN: incomplete profile slot ignored" CR 0 EXIT THEN
  DUP 8 + C@ 1 33 WITHIN 0= IF DROP 2 EXIT THEN
  DUP 76 SHA1-DIGEST OVER 76 + 20 BYTES= NIP SHA1-CLEAR IF 1 ELSE 2 THEN ;
: CURRENT ( -- a ) ACTIVE @ IF REC-B ELSE REC-A THEN ;
: READ-SLOTS ( -- )
  -1 ACTIVE !
  SLOT-A REC-A 128 FLASH-READ THROW SLOT-B REC-B 128 FLASH-READ THROW
  REC-A VALID VALID-A ! REC-B VALID VALID-B !
  VALID-A @ 2 = VALID-B @ 2 = OR IF ." WLAN: damaged profile slot" CR THEN
  VALID-A @ 1 = VALID-B @ 1 = AND IF
    REC-A 4 + @ REC-B 4 + @ - DUP 0= IF DROP -430 THROW THEN
    0< IF 1 ELSE 0 THEN ACTIVE ! EXIT
  THEN
  VALID-A @ 1 = IF 0 ACTIVE ! EXIT THEN
  VALID-B @ 1 = IF 1 ACTIVE ! EXIT THEN
  VALID-A @ 2 = VALID-B @ 2 = OR IF -430 THROW THEN ;
: ADDRESS ( i -- faddr ) IF SLOT-B ELSE SLOT-A THEN ;
: (SAVE) ( -- )
  WIFI-STATUS 6 <> ABORT" WLAN: save only after a successful join"
  READ-SLOTS
  ACTIVE @ 0< IF 0 DESTINATION ! 1 NEXT-SEQ !
  ELSE 1 ACTIVE @ - DESTINATION ! CURRENT 4 + @ 1+ NEXT-SEQ ! THEN
  WORK 128 0 FILL MAGIC WORK ! NEXT-SEQ @ WORK 4 + !
  STA-SLEN @ WORK 8 + C! STA-SSID WORK 12 + STA-SLEN @ MOVE STA-PMK WORK 44 + 32 MOVE
  WORK 76 SHA1-DIGEST WORK 76 + 20 MOVE SHA1-CLEAR
  DESTINATION @ ADDRESS 4096 FLASH-ERASE THROW
  WORK 96 DESTINATION @ ADDRESS FLASH-WRITE THROW
  COMMIT WORK 96 + ! WORK 96 + 4 DESTINATION @ ADDRESS 96 + FLASH-WRITE THROW
  WORK REC-A 100 MOVE DESTINATION @ ADDRESS WORK 128 FLASH-READ THROW
  WORK REC-A 100 BYTES= 0= IF -432 THROW THEN ." WLAN profile saved" CR ;
: (SAVED?) ( -- f ) READ-SLOTS ACTIVE @ 0< 0= ;
: (JOIN) ( i -- )
  WIFI-STATUS 0<> ABORT" WLAN: leave before loading a saved profile"
  READ-SLOTS ACTIVE @ 0< IF -431 THROW THEN CURRENT WORK 128 MOVE
  DUP WIFI-NET 2DROP DUP WORK 8 + C@ = 0= ABORT" WLAN: selected SSID differs from saved profile"
  WORK 12 + SWAP BYTES= 0= ABORT" WLAN: selected SSID differs from saved profile"
  WORK 44 + WIFI-JOIN ;
: (FORGET) ( -- )
  SLOT-A 4096 FLASH-ERASE THROW SLOT-B 4096 FLASH-ERASE THROW WIFI-LEAVE ;
: EXECUTE-CLEAN ( xt -- ) CATCH WIPE THROW ;
PUBLIC
: WLAN-SAVE ( -- ) ['] (SAVE) EXECUTE-CLEAN ;
: WLAN-SAVED? ( -- f ) ['] (SAVED?) EXECUTE-CLEAN ;
: WLAN-JOIN ( i -- ) ['] (JOIN) EXECUTE-CLEAN ;
: WLAN-FORGET ( -- ) ['] (FORGET) EXECUTE-CLEAN ;
END-PACKAGE
