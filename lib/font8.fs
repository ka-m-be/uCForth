\ font8.fs - package FONT8: a font of 8 x 8 pixels for the characters 32 to 126
\
\ Each character is 8 bytes, the top row first. In a byte, bit 0 is the
\ pixel at the left. >GLYPH gives the address of the 8 bytes; a character
\ outside 32 to 126 gets the pattern of "?".
\
\ The font is public domain: the VGA font of IBM, by Marcel Sondaar, as
\ font8x8_basic by Daniel Hepper (github.com/dhepper/font8x8).

